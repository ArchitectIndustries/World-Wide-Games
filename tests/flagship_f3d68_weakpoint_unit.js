'use strict';
const assert=require('node:assert/strict');
const W=require('../games/aegis-verge/armor-weakpoint.js');
const A=require('../games/aegis-verge/enemy-armor-wear.js');
const ES=require('../games/aegis-verge/enemy-silhouettes.js');
let n=0;const ok=(name,value)=>{assert.ok(value,name);n++};
const base={x:0,z:0,yaw:0,size:1.7,hp:4,max:8,type:'lancer',dead:false};
const fromRight={vx:-45,vz:0},contact={x:1.1,z:0};
const test=(e=base,s=fromRight,c=contact,d=1)=>W.evaluate(e,s,c,d);
ok('frozen module',Object.isFrozen(W)&&Object.isFrozen(W.ALLOWED));
ok('no attack without enemy',test(null).bonus===0);
ok('exact half HP opens right conduit',test().bonus===1);
ok('bonus added to actual positive damage',test(base,fromRight,contact,2).damage===3);
ok('full HP not open',test({...base,hp:8}).bonus===0);
ok('above half does not open',test({...base,hp:5}).bonus===0);
ok('below half opens',test({...base,hp:2}).bonus===1);
ok('dead enemy no weakpoint',test({...base,dead:true}).bonus===0);
ok('zero HP no weakpoint',test({...base,hp:0}).bonus===0);
ok('unbounded HP max rejected',test({...base,max:0}).bonus===0);
ok('Warden remains exclusive',test({...base,type:'warden'}).bonus===0);
ok('unknown type ignored',test({...base,type:'unknown'}).bonus===0);
ok('left-side contact not a weakpoint',test(base,fromRight,{x:-1,z:0}).bonus===0);
ok('front center contact not weakpoint',test(base,fromRight,{x:0,z:1}).bonus===0);
ok('right-side outward travel not a flank',test(base,{vx:40,vz:0},contact).bonus===0);
ok('sideways graze not a flank',test(base,{vx:0,vz:40},contact).bonus===0);
ok('reflection cannot earn bonus',test(base,{...fromRight,reflected:true}).bonus===0);
ok('invalid shot vector excluded',test(base,{vx:Infinity,vz:0}).bonus===0);
ok('zero travel excluded',test(base,{vx:0,vz:0}).bonus===0);
ok('missing contact excluded',test(base,fromRight,null).bonus===0);
ok('invalid contact excluded',test(base,fromRight,{x:Infinity,z:0}).bonus===0);
ok('missing yaw excluded',test({...base,yaw:NaN}).bonus===0);
ok('zero base damage never fabricates base damage',test(base,fromRight,{x:0,z:0},0).damage===0);
for(const type of W.ALLOWED){
 ok(type+' opens exactly when armor visually removed',A.stage({...base,type,hp:4})===2&&test({...base,type}).bonus===1);
 ok(type+' visual unbroken armor has no weakpoint',A.stage({...base,type,hp:8})===0&&test({...base,type,hp:8}).bonus===0);
 ok(type+' conduit is visible at half hp',ES.parts({...base,type},'lite',0,true).some(p=>p.name==='exposed-conduit'));
}
const rot=Math.PI/2;
ok('yaw 90-degree local-right becomes -world-z',test({...base,yaw:rot},{vx:0,vz:35},{x:0,z:-1}).bonus===1);
ok('yaw 90-degree opposite entry blocked',test({...base,yaw:rot},{vx:0,vz:-35},{x:0,z:-1}).bonus===0);
ok('right contact threshold strict',test(base,fromRight,{x:.1,z:0}).bonus===0);
ok('lit reaction only on authoritative hit',!ES.parts(base,'full',3,false).some(p=>p.name==='breach-spark'));
ok('reaction has new emissive geometry',ES.parts({...base,weakpointFlash:.4},'full',3,false).some(p=>p.name==='breach-spark'));
ok('low-tier reaction limits extra geometry',!ES.parts({...base,weakpointFlash:.4},'lite',3,false).some(p=>p.name==='breach-spark'));
ok('calm mode preserves exposed conduit without flash',ES.parts(base,'lite',3,true).some(p=>p.name==='exposed-conduit'));
ok('flash is cosmetic only and respects HP state',!ES.parts({...base,hp:8,weakpointFlash:.4},'full',3,false).some(p=>p.name==='breach-spark'));
console.log(`F3D68 exposed conduit unit ${n}/${n} passed`);
