'use strict';
const assert=require('node:assert/strict');
const C=require('../games/aegis-verge/flux-capacitors.js');
const P=require('../games/aegis-verge/flux-phase-screens.js');
const T=require('../games/aegis-verge/tactics.js');
let count=0;
const check=(description,callback)=>{callback();count++};
const line=(s,prog=1,armed=true,from=[3.2,-25],to=[3.2,-17])=>C.intercept(s,prog,armed,...from,...to,T.segmentCircle);
check('two fixed first-party node locations',()=>assert.deepEqual(C.NODES.map(n=>n.progress),[1,3]));
check('HP exactly two hits',()=>assert.equal(C.HP,2));
check('constrained physical shot radius',()=>assert(C.RADIUS>0&&C.RADIUS<=1));
check('no score or loot authority',()=>assert(!('score'in C)&&!('reward'in C)));
check('unstarted circuit not armable',()=>assert.equal(line(C.create(),1,false),null));
check('wrong progress not armable',()=>assert.equal(line(C.create(),0),null));
check('return inactive on departure leg',()=>assert.equal(line(C.create(),3),null));
check('unrelated shot misses',()=>assert.equal(line(C.create(),1,true,[0,-25],[0,-17]),null));
check('nonfinite shot ignored',()=>assert.equal(line(C.create(),1,true,[NaN,0],[3,-18]),null));
check('segment passing before target misses',()=>assert.equal(line(C.create(),1,true,[3.2,-25],[3.2,-24]),null));
check('segment after target misses',()=>assert.equal(line(C.create(),1,true,[3.2,-17],[3.2,-15]),null));
check('contact bounded',()=>{const hit=line(C.create());assert(hit&&hit.t>0&&hit.t<1)});
const s=C.create(),contact=line(s);
check('first hit damages exactly one HP',()=>assert.equal(C.hit(s,contact).hp,1));
check('first hit does not disable',()=>assert.equal(C.disabled(s,'departure'),false));
check('second hit disables',()=>assert.equal(C.hit(s,contact).down,true));
check('two hits tracked separately',()=>assert.equal(s.hits,2));
check('exactly one shutdown',()=>assert.equal(s.disabled,1));
check('disabled node is not targetable',()=>assert.equal(line(s),null));
check('disabled node cannot be hit twice',()=>assert.equal(C.hit(s,contact),null));
check('no duplicate hits or penalties',()=>assert.deepEqual([s.hits,s.disabled],[2,1]));
check('unknown node not considered disabled',()=>assert.equal(C.disabled(s,'unknown'),false));
check('return node still full health',()=>assert.deepEqual(s.hp,[0,2]));
check('two distinct screens can disable',()=>{const r=C.intercept(s,3,true,-3.2,30,-3.2,23,T.segmentCircle);assert(r);assert.equal(C.hit(s,r).hp,1);assert.equal(C.hit(s,r).down,true);});
check('fully disabled status',()=>assert.deepEqual(s.hp,[0,0]));
check('hazard old logic still live when intact',()=>{const p=P.create();const t=P.OPEN+P.WARN+.2-P.SCREENS[0].offset;assert.equal(P.inspect(p,{x:0,z:-20},{x:0,z:-19},1,t,0,false,C.create()).kind,'hit')});
check('disabled crossing now safe',()=>{const p=P.create();const t=P.OPEN+P.WARN+.2-P.SCREENS[0].offset;assert.equal(P.inspect(p,{x:0,z:-20},{x:0,z:-19},1,t,0,false,s).kind,'disabled');assert.equal(p.hits,0)});
check('offline HUD announces practice',()=>assert.match(P.status(P.create(),1,3,0,s),/OFFLINE — PRACTICE/));
check('active HUD warning remains',()=>assert.match(P.status(P.create(),1,P.OPEN+P.WARN+.2-P.SCREENS[0].offset,0,C.create()),/LIVE/));
check('reactor renderer null safe',()=>assert.equal(C.render(null,s,1),0));
const calls=[];
check('reactor renderer uses first-party 3D geometry',()=>assert(C.render({cube(...a){calls.push(a)}},C.create(),1)>9&&calls.length>9));
check('disabled reactor clearly changes to green',()=>{calls.length=0;C.render({cube(...a){calls.push(a)}},s,1);assert(calls.some(c=>c.includes('#34d399')))});
check('screen rendering turns off pink field',()=>{calls.length=0;P.render({cube(...a){calls.push(a)}},false,false,1,3,0,s);assert(!calls.some(c=>c[6]==='#fb7185'))});
check('invalid forged hit cannot mutate state',()=>{const b=C.create();assert.equal(C.hit(b,{index:99,id:'fake'}),null);assert.deepEqual(b.hp,[2,2]);});
check('state reset restores both nodes',()=>assert.deepEqual(C.create().hp,[2,2]));
console.log(`F3D50 Flux Capacitor Interdiction ${count}/${count} assertions passed`);
