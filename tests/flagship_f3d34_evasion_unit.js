'use strict';
const assert=require('node:assert/strict');require('../games/aegis-verge/slipstream-evasion.js');
const S=globalThis.AegisSlipstreamEvasion;let count=0;const ok=(name,fn)=>{fn();count++;};
const p={x:0,z:0,energy:50},g=(ax,az,bx,bz,wall=Infinity,decoy=Infinity)=>S.probe(ax,az,bx,bz,p,wall,decoy);
ok('initial state finite',()=>assert.deepEqual(S.create(),{cooldown:0,flash:0,count:0}));
ok('real side near-miss',()=>assert.ok(g(-3,2,3,2)));
ok('actual sweep coordinate',()=>assert.equal(g(-3,2,3,2).x,0));
ok('actual sweep positive mid time',()=>assert.equal(g(-3,2,3,2).t,.5));
ok('real body collision not a graze',()=>assert.equal(g(-3,0,3,0),null));
ok('collision radius margin',()=>assert.equal(g(-3,1.4,3,1.4),null));
ok('outside near miss radius',()=>assert.equal(g(-3,3,3,3),null));
ok('zero length segment rejected',()=>assert.equal(g(0,2,0,2),null));
ok('invalid coordinates rejected',()=>assert.equal(S.probe(NaN,0,3,2,p),null));
ok('far endpoint only rejected',()=>assert.equal(g(-3,2,0,2),null));
ok('spawn adjacency only rejected',()=>assert.equal(g(0,2,3,2),null));
ok('solid wall before graze rejects',()=>assert.equal(g(-3,2,3,2,.4),null));
ok('solid wall after graze allows',()=>assert.ok(g(-3,2,3,2,.8)));
ok('decoy first rejects',()=>assert.equal(g(-3,2,3,2,Infinity,.1),null));
ok('decoy later allows',()=>assert.ok(g(-3,2,3,2,Infinity,.9)));
ok('non finite player rejected',()=>assert.equal(S.probe(-3,2,3,2,{x:NaN,z:0}),null));
ok('unshielded real movement awards',()=>{let a=S.create(),b={life:2},v={...p};assert.ok(S.reward(a,b,v,g(-3,2,3,2),.2));assert.equal(v.energy,56);assert.equal(a.count,1);});
ok('standing still no reward',()=>assert.equal(S.reward(S.create(),{}, {...p},g(-3,2,3,2),0),false));
ok('frozen, tiny movement no reward',()=>assert.equal(S.reward(S.create(),{}, {...p},g(-3,2,3,2),.005),false));
ok('shielded no reward',()=>assert.equal(S.reward(S.create(),{}, {...p},g(-3,2,3,2),.2,true),false));
ok('same bolt never repeats',()=>{const a=S.create(),b={},v={...p};S.reward(a,b,v,g(-3,2,3,2),.2);S.tick(a,2);assert.equal(S.reward(a,b,v,g(-3,2,3,2),.2),false);});
ok('cooldown stops volley farming',()=>{const a=S.create(),v={...p};S.reward(a,{},v,g(-3,2,3,2),.2);assert.equal(S.reward(a,{},v,g(-3,2,3,2),.2),false)});
ok('cooldown ticks by simulation time only',()=>{const a=S.create();a.cooldown=1;a.flash=.4;S.tick(a,.3);assert.ok(Math.abs(a.cooldown-.7)<1e-10);S.tick(a,0);assert.ok(Math.abs(a.cooldown-.7)<1e-10)});
ok('cooldown recovers after simulation time',()=>{const a=S.create(),v={...p};S.reward(a,{},v,g(-3,2,3,2),.2);S.tick(a,1.3);assert.ok(S.reward(a,{},v,g(-3,2,3,2),.2));assert.equal(a.count,2)});
ok('reward clamped to 100',()=>{const a=S.create(),v={...p,energy:98};assert.ok(S.reward(a,{},v,g(-3,2,3,2),.2));assert.equal(v.energy,100)});
ok('no extra grant at 100',()=>assert.equal(S.reward(S.create(),{}, {...p,energy:100},g(-3,2,3,2),.2),false));
ok('render calm limits draw count',()=>{let k=0;S.render({cube(){k++}},p,{flash:.4},true);assert.equal(k,4)});
ok('render full bounded ten calls',()=>{let k=0;S.render({cube(){k++}},p,{flash:.4},false);assert.equal(k,10)});
ok('render faded does not allocate',()=>{let k=0;S.render({cube(){k++}},p,{flash:0},false);assert.equal(k,0)});
console.log(JSON.stringify({passed:count,failed:0,feature:'F3D34 Slipstream Evasion'}));
