'use strict';
const assert=require('node:assert/strict');
const DM=require('../games/aegis-verge/skyburst-demolition.js');
const SB=require('../games/aegis-verge/siege-barrage.js');
const BC=require('../games/aegis-verge/breachable-cover.js');
const T=require('../games/aegis-verge/tactics.js');
let total=0;const ok=(label,value)=>{assert.ok(value,label);total++};
const base=T.coverFor(0),state=BC.create(base),cover=BC.live(state);
const b=base[0],shell={x:b.x+b.w/2+1.2,z:b.z};
const select=(s=shell,c=cover,st=state)=>DM.impacted(s,c,id=>BC.status(st,id)?.hp??0,T.firstCover,SB.RADIUS);
let hits=select();
ok('first party structural blast is fixed and bounded',DM.DAMAGE===3);
ok('eligible destructible cover is selected by real collision records',hits.some(h=>h.block.id===0));
ok('indestructible concrete stays immune',!hits.some(h=>h.block.id===1));
ok('result has contact on real rectangle face',hits.find(h=>h.block.id===0).point.x===b.x+b.w/2);
ok('first artillery shell strikes 5 HP barricade down to 2 HP',BC.strike(state,0,DM.DAMAGE).hp===2);
ok('not destroyed in a single burst',BC.status(state,0).breached===false);
ok('second shell breaches original cover',BC.strike(state,0,DM.DAMAGE).breached);
ok('real cover list no longer includes breached geometry',!BC.live(state).some(q=>q.id===0));
ok('no duplicate structural hits on destroyed cover',select(shell,BC.live(state),state).every(q=>q.block.id!==0));
const newState=BC.create(base);let pureBefore=BC.snapshot(newState);
DM.impacted(shell,BC.live(newState),id=>BC.status(newState,id)?.hp??0,T.firstCover,SB.RADIUS);
ok('candidate selection has no gameplay HP side effects',JSON.stringify(BC.snapshot(newState))===JSON.stringify(pureBefore));
ok('checkpoint serializes blast damage',BC.restore(newState,[2,5,5]));
ok('checkpoint restores 2-HP damaged barricade',BC.status(newState,0).hp===2);
ok('checkpoint restores intact other barricades',BC.status(newState,3).hp===5);
const single={id:0,x:0,z:0,w:2,d:2};
const withCover=[single,{id:77,x:3,z:0,w:.5,d:4}];
const imp={x:5,z:0};
ok('outer edge beyond blast circle excluded',DM.impacted(imp,[single],()=>5,T.firstCover,2).length===0);
ok('other solid cover blocks radial structural hit',DM.impacted(imp,withCover,id=>id===0?5:0,T.firstCover,7).length===0);
ok('open line permits radial damage',DM.impacted(imp,[single],()=>5,T.firstCover,7).length===1);
ok('impact within rectangular footprint permitted',DM.impacted({x:0,z:0},[single],()=>5,T.firstCover,2).length===1);
ok('nonstructural obstacles never hit',DM.impacted(imp,withCover,()=>0,T.firstCover,7).length===0);
ok('NaN shell rejected',DM.impacted({x:NaN,z:1},[single],()=>5,T.firstCover,7).length===0);
ok('no firstCover callback rejected',DM.impacted(imp,[single],()=>5,null,7).length===0);
ok('negative radius rejected',DM.impacted(imp,[single],()=>5,T.firstCover,-1).length===0);
ok('bad block width rejected',DM.impacted(imp,[{id:1,x:0,z:0,w:-2,d:2}],()=>5,T.firstCover,7).length===0);
ok('bad block identity rejected',DM.impacted(imp,[{id:1.1,x:0,z:0,w:2,d:2}],()=>5,T.firstCover,7).length===0);
const noCover=DM.impacted({x:0,z:0},[{id:0,x:0,z:0,w:1,d:1}],()=>5,T.firstCover,4);
ok('zero distance correctly handled by segment-only authority',noCover.length===1);
console.log(JSON.stringify({feature:'Skyburst Demolition original blast/cover intersection and checkpoint',passed:total,failed:0}));
