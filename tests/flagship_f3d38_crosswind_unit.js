
'use strict';
const assert=require('node:assert/strict');
const SB=require('../games/aegis-verge/siege-barrage.js');
const T=require('../games/aegis-verge/tactics.js');
let n=0;const ok=(name,check)=>{assert.ok(check,name);n++};
const caster={type:'warden',idx:7,x:0,z:0,cycles:2};
const shells=[];const shell=SB.launch(shells,caster,{x:12,z:0});
ok('shell carries authoritative firing index',shell.casterIdx===7);
const units=[{idx:7,x:12,z:0,hp:8},{idx:2,x:11,z:1,hp:2},{idx:3,x:14,z:1,hp:5},{idx:4,x:18,z:0,hp:2},{idx:5,x:13,z:0,dead:true},{idx:6,x:8,z:0,hp:2}];
const hit=SB.splashHostiles(shell,units,[],T.firstCover);
ok('real enemies inside impact are caught',hit.length===3);
ok('firing Warden is immune',!hit.some(h=>h.enemy.idx===7));
ok('dead hostiles are excluded',!hit.some(h=>h.enemy.idx===5));
ok('outside ring excluded',!hit.some(h=>h.enemy.idx===4));
ok('fixed 2 HP enemy blast damage',SB.HOSTILE_DAMAGE===2);
const cover=[{id:18,x:12.5,z:0,w:.6,d:3,h:4}];
const protectedUnits=SB.splashHostiles(shell,units,cover,T.firstCover);
ok('occluded enemy excluded',!protectedUnits.some(h=>h.enemy.idx===3));
ok('same side enemy still caught',protectedUnits.some(h=>h.enemy.idx===2));
ok('safe invalid callback',SB.splashHostiles(shell,units,cover,null).length===0);
ok('safe invalid shell',SB.splashHostiles({},units,[],T.firstCover).length===0);
ok('does not mutate enemy HP',units[1].hp===2);
ok('does not mutate enemy dead state',!units[1].dead);
const outcome=SB.step(shells,SB.FLIGHT,{x:30,z:30},[],T.firstCover)[0];
ok('detonation carries firing identity for original-game callback',outcome.casterIdx===7);
ok('dodge of player does not cancel hostile area effect',!outcome.hit&&SB.splashHostiles(outcome,units,[],T.firstCover).length===3);
ok('real shell expiry',shells.length===0);
ok('no infinite duplicate hits on same expiry',SB.step(shells,.5,{x:12,z:0},[],T.firstCover).length===0);
console.log(JSON.stringify({feature:'Crosswind, cover-blocked Warden friendly fire',passed:n,failed:0}));
