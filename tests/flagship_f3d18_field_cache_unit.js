/* First-party, deterministic field-salvage and checkpoint tests. */
const assert=require('node:assert/strict');
const FC=require('../games/aegis-verge/field-cache.js');
const CP=require('../games/aegis-verge/checkpoint.js');
const sites=[{x:2,z:3},{x:12,z:3},{x:20,z:3}];
let passed=0;const ck=(condition,message)=>{assert.ok(condition,message);passed++};
const actor=(x=2,z=3,hull=50,energy=25)=>({x,z,hull,energy});
let s=FC.create(sites),p=actor(),wall=[];
ck(FC.COUNT===3&&FC.CHANNEL>1,'three stations have finite risk channel');
ck(FC.valid([false,true,false]),'valid booleans accepted');
ck(!FC.valid([0,1,0]),'numeric flags rejected');
ck(!FC.valid([true,false]),'missing slot rejected');
ck(!FC.valid([true,false,false,false]),'surplus slot rejected');
ck(FC.ready(s,0,p,wall,()=>null),'nearby depleted player can start');
ck(!FC.ready(s,1,p,wall,()=>null),'far cache inaccessible');
ck(!FC.ready(s,0,actor(2,3,100,100),wall,()=>null),'cannot squander full resources');
ck(!FC.ready(s,0,p,wall,()=>({t:.5})),'real cover blocks interaction');
ck(FC.begin(s,0,p,wall,()=>null),'begin channel');
ck(!FC.begin(s,0,p,wall,()=>null),'no overlapping channel');
ck(FC.tick(s,p,.4,false,wall,()=>null)==='channeling','partial time');
ck(s.left<FC.CHANNEL&&s.left>0,'countdown decremented');
ck(s.used[0]===false&&p.hull===50,'partial channel has no reward');
ck(FC.tick(s,p,1,false,wall,()=>null)?.type==='recovered','channel completes');
ck(p.hull===72&&p.energy===57,'real hull and energy gain');
ck(FC.snapshot(s)[0]===true,'station spent');
ck(!FC.begin(s,0,p,wall,()=>null),'cannot farm spent cache');
ck(s.channel===-1&&s.left===0,'channel clears after use');
let q=FC.create(sites);p=actor();ck(FC.begin(q,0,p,wall,()=>null),'begin motion fixture');p.x+=1.2;
ck(FC.tick(q,p,.5,false,wall,()=>null)==='interrupted','moving cancels channel');
ck(!q.used[0]&&p.hull===50,'motion cancel no score/resources');
p=actor();ck(FC.begin(q,0,p,wall,()=>null),'restart after interrupted motion');
ck(FC.tick(q,p,.1,true,wall,()=>null)==='interrupted','shield cancels');
ck(!q.used[0],'shield cancel not spent');
ck(FC.begin(q,0,p,wall,()=>null),'re-arm after shield interruption');p.hull=49;
ck(FC.tick(q,p,.1,false,wall,()=>null)==='interrupted','damage interrupts');
ck(!q.used[0],'damaged station reusable');
p=actor();ck(FC.begin(q,0,p,wall,()=>null),'start obstructed fixture');
ck(FC.tick(q,p,.1,false,wall,()=>({t:.2}))==='interrupted','new obstruction cancels channel');
ck(!q.used[0],'obstructed station not consumed');
p=actor(2,3,96,96);ck(FC.begin(q,0,p,wall,()=>null),'partial repair at near full');
let reward=FC.tick(q,p,FC.CHANNEL,false,wall,()=>null);
ck(reward.hull===4&&reward.energy===4,'resources clamp to 100');
ck(p.hull===100&&p.energy===100,'player resource caps enforced');
ck(FC.snapshot(q).join(',')==='true,false,false','single station consumption');
ck(FC.cancel(q)===false,'idle cancel idempotent');
ck(FC.tick(q,p,-2,false,wall,()=>null)===null,'negative time ignored');
ck(FC.create(sites,[true,false,true]).used[2]===true,'checkpoint restore spent state');
ck(FC.create(sites,[true,false,true]).channel===-1,'checkpoint never resumes channel');
let error=false;try{FC.create(sites,[1,0,1])}catch{error=true}ck(error,'invalid restore rejected');
const storage=new Map(),store={getItem:k=>storage.get(k)??null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)};
const snapshot={op:0,relay:1,hull:70,energy:80,score:700,recoveriesLeft:1,elapsed:45,damageTaken:30,clean:false,barrierHp:[5,5,5],uplinkUsed:[false,false,false],mineHp:[2,2,2],cacheUsed:[true,false,false]};
ck(CP.save(store,snapshot),'new checkpoint saved with spent cache');
ck(JSON.stringify(CP.load(store,1).cacheUsed)==='[true,false,false]','new checkpoint reload immutable flags');
ck(!CP.validate({...snapshot,cacheUsed:[true,1,false],version:1,savedAt:Date.now()}),'malformed cache flags rejected');
ck(!CP.validate({...snapshot,cacheUsed:[true,false],version:1,savedAt:Date.now()}),'truncated cache flags rejected');
ck(JSON.stringify(CP.validate({...snapshot,cacheUsed:undefined,version:1,savedAt:Date.now()}).cacheUsed)==='[false,false,false]','old v1 checkpoint defaults to unspent');
ck(CP.clear(store)&&CP.load(store,1)===null,'checkpoint clear safe');
console.log(JSON.stringify({suite:'F3D18 field salvage',passed,total:passed}));
