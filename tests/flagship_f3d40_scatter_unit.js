'use strict';
const assert=require('node:assert/strict');
const S=require('../games/aegis-verge/skyburst-scatter.js');
const T=require('../games/aegis-verge/tactics.js');
const SB=require('../games/aegis-verge/siege-barrage.js');
let n=0;const ok=(name,value)=>{assert.ok(value,name);n++};
const sk=(extra={})=>({type:'skirmisher',idx:2,x:0,z:2,dead:false,state:'seek',path:[{x:3,z:2}],navAt:5,travelDistance:0,motionRate:0,yaw:0,hp:2,...extra});
const shell=(extra={})=>({x:0,z:0,left:.45,casterIdx:1,...extra});
const step=(e=sk(),sh=[shell()],blocks=[],dt=1/60)=>S.evade(e,sh,dt,blocks,T,SB.RADIUS);
let e=sk(),start={...e};ok('live uncovered skirmisher responds',step(e));
ok('movement increases actual distance from impact',Math.hypot(e.x,e.z)>Math.hypot(start.x,start.z));
ok('movement only covers bounded distance',Math.hypot(e.x-start.x,e.z-start.z)<=4.3*S.BOOST/60+1e-7);
ok('real locomotion stores distance for animated fins',e.travelDistance>0&&e.motionRate>0);
ok('real navigation path invalidated',e.path.length===0&&e.navAt===0);
ok('evasion changes state only, not HP',e.state==='evade'&&e.hp===2);
ok('early shell offers no premature evasion',!step(sk(),[shell({left:.7})]));
ok('expired shell cannot trigger escape',!step(sk(),[shell({left:0})]));
ok('no shell no dodge',!step(sk(),[]));
ok('skirmisher beyond danger does not flee',!step(sk({z:SB.RADIUS+S.BUFFER+1})));
ok('lancer deliberately stays lureable',!step(sk({type:'lancer'})));
ok('bulwark deliberately stays lureable',!step(sk({type:'bulwark'})));
ok('warden deliberately stays lureable',!step(sk({type:'warden'})));
ok('committed attack cannot be cancelled',!step(sk({state:'windup'})));
ok('staggered unit cannot be interrupted',!step(sk({state:'stagger'})));
ok('dead unit cannot move',!step(sk({dead:true})));
ok('safety rejects invalid dt 0',!step(sk(),[shell()],[],0));
ok('safety rejects large dt spike',!step(sk(),[shell()],[],1));
ok('safety rejects NaN shell positions',!step(sk(),[shell({x:NaN})]));
ok('safety rejects negative blast radius',!S.evade(sk(),[shell()],1/60,[],T,-1));
ok('skirmisher behind intact solid cover does not react',!step(sk({x:5,z:0}),[shell()], [{id:1,x:2,z:0,w:1,d:5}]));
let blocked=sk({x:36.9,z:0});ok('world edge prevents moving outside perimeter',!step(blocked,[shell({x:36.9,z:0})] )||Math.abs(blocked.x)<=38);
ok('centered overlapping impact yields valid deterministic bearing',(()=>{const a=sk({x:0,z:0});const v=step(a);return v&&Number.isFinite(a.x)&&Number.isFinite(a.z)&&Math.hypot(a.x,a.z)>0;})());
let x=sk();const snapshot=JSON.stringify([x.x,x.z,x.hp]);ok('scattered enemy never changes player score or salvage channels',step(x)&&JSON.stringify([x.hp])==='[2]');
ok('caller-owned list remains immutable',(()=>{let list=[shell()];step(sk(),list);return list.length===1&&list[0].left===.45;})());
console.log(JSON.stringify({suite:'F3D40 first-party Skyburst Scatter enemy tactic; pure collision and state semantics',passed:n,total:n,failed:0}));
