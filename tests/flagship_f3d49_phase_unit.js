'use strict';
const assert=require('node:assert/strict'),F=require('../games/aegis-verge/flux-phase-screens.js');
let count=0;const check=(name,fn)=>{fn();count++};
const from=(z,x=0)=>({z,x}),to=(z,x=0)=>({z,x}),a=F.SCREENS[0],b=F.SCREENS[1];
const live=F.OPEN+F.WARN+.2-a.offset,open=.3-a.offset+F.PERIOD;
check('two separate course screens',()=>assert.equal(F.SCREENS.length,2));
check('no offensive scoring authority',()=>assert.equal('score' in F,false));
check('no direct movement authority',()=>assert.equal('move' in F,false));
check('phase defaults inactive without real started clock',()=>assert.equal(F.phase(a,5,null),'idle'));
check('open phase deterministic',()=>assert.equal(F.phase(a,open,0),'open'));
check('warning phase deterministic',()=>assert.equal(F.phase(a,F.OPEN+.1-a.offset,0),'warning'));
check('active phase deterministic',()=>assert.equal(F.phase(a,live,0),'live'));
check('safe wrap across period',()=>assert.equal(F.phase(a,open+F.PERIOD,0),'open'));
check('pause safe: same clock same phase',()=>assert.equal(F.phase(a,live,0),F.phase(a,live,0)));
check('no active screen before first gate',()=>assert.equal(F.current(0),null));
check('outbound after gate 1',()=>assert.equal(F.current(1),a));
check('none between legs',()=>assert.equal(F.current(2),null));
check('return after gate 3',()=>assert.equal(F.current(3),b));
check('none after full course',()=>assert.equal(F.current(4),null));
const s=F.create();
check('wrong progression does nothing',()=>assert.equal(F.inspect(s,from(-19.8),to(-18.8),0,live,0),null));
check('unstarted course cannot damage',()=>assert.equal(F.inspect(s,from(-19.8),to(-18.8),1,live,null),null));
check('no hit from stationary player',()=>assert.equal(F.inspect(s,from(-19.5),to(-19.5),1,live,0),null));
check('wrong travel direction ignored',()=>assert.equal(F.inspect(s,from(-18.5),to(-20.0),1,live,0),null));
check('side of screen beyond lane ignored',()=>assert.equal(F.inspect(s,from(-20,2.5),to(-18,2.5),1,live,0),null));
check('uncrossed segment ignored',()=>assert.equal(F.inspect(s,from(-20),to(-19.5),1,live,0),null));
check('valid world-space swept crossing hits live field',()=>assert.equal(F.inspect(s,from(-20),to(-18),1,live,0).kind,'hit'));
check('one hit recorded',()=>assert.equal(s.hits,1));
check('same screen cannot charge twice',()=>assert.equal(F.inspect(s,from(-20),to(-18),1,live+1,0),null));
check('returned hit location lies on real plane',()=>assert.equal(s.last.z,a.z));
const sh=F.create();
check('shielded live crossing is guarded',()=>assert.equal(F.inspect(sh,from(-20),to(-18),1,live,0,true).kind,'guard'));
check('shielded pass never counts hit',()=>assert.deepEqual([sh.hits,sh.guards],[0,1]));
const so=F.create();
check('open window is safe crossing',()=>assert.equal(F.inspect(so,from(-20),to(-18),1,open,0).kind,'safe'));
check('open window not hit',()=>assert.equal(so.hits,0));
const sw=F.create();
check('warning remains safe crossing',()=>assert.equal(F.inspect(sw,from(-20),to(-18),1,F.OPEN+.1-a.offset,0).kind,'safe'));
const rt=F.create();
check('return screen requires opposite direction',()=>assert.equal(F.inspect(rt,from(25),to(26),3,F.OPEN+F.WARN+.2-b.offset,0),null));
check('return live crossing hits',()=>assert.equal(F.inspect(rt,from(26),to(24),3,F.OPEN+F.WARN+.2-b.offset,0).kind,'hit'));
check('status expresses actionable active warning',()=>assert.match(F.status(F.create(),1,live,0),/SHIELD \/ WAIT/));
check('status includes hit history',()=>assert.match(F.status(s,1,live,0),/1 STRIKE/));
check('status returns standby when inactive',()=>assert.equal(F.status(F.create(),0,0,null),'STANDBY'));
check('radius not arbitrarily widened',()=>assert.equal(F.WIDTH,1.95));
check('penalties finite bounded',()=>assert(F.HULL>0&&F.HULL<20&&F.ENERGY>0&&F.ENERGY<20));
check('renderer no-op null safely',()=>assert.equal(F.render(null,false,false,1,live,0),undefined));
const calls=[];F.render({cube(...v){calls.push(v)}},false,false,1,live,0);
check('live state renders real 3D beam segments',()=>assert(calls.length>=9&&calls.some(c=>c[6]==='#fb7185')));
console.log(`F3D49 Flux Phase Screens ${count}/${count} assertions passed`);
