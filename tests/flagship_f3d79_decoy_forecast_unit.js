/* F3D79: decoy should suppress a crossfire forecast only if it can intercept first. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'../games/aegis-verge');
const V=require(path.join(root,'crossfire-preview.js'));
const HT=require(path.join(root,'hostile-telegraphs.js'));
const CF=require(path.join(root,'hostile-crossfire.js'));
const T=require(path.join(root,'tactics.js'));
const TD=require(path.join(root,'tactical-decoy.js'));
const types={lancer:{size:1.7},bulwark:{size:2.1}};
const shooter=()=>({idx:0,x:0,z:-10,hp:3,state:'windup',type:'lancer',aimX:0,aimZ:20});
const ally=()=>({idx:1,x:0,z:0,hp:8,state:'seek',type:'bulwark'});
const player={x:0,z:15};
const callback=(d,ax,az,bx,bz)=>TD.hitTime(d,ax,az,bx,bz,T);
const observe=(d,cb=callback,e=[shooter(),ally()],p=player,firstCover=()=>null)=>V.observe(p,e,[],firstCover,T.segmentCircle,HT,CF,types,d,cb);
let checks=0;function check(label,actual,expected){assert.deepEqual(actual,expected,label);checks++}
const distant={x:12,z:-4,left:5,hp:2};
const intercepting={x:0,z:-5,left:5,hp:2};
const behind={x:0,z:8,left:5,hp:2};
check('baseline cue without decoy',!!observe(null),true);
check('confirmed pre-fix bug: missing callback hides all active-decoy cues',observe(distant,null),null);
check('far-away decoy must NOT suppress crossfire',!!observe(distant),true);
check('decoy behind prospective ally must NOT suppress crossfire',!!observe(behind),true);
check('decoy earlier than ally DOES suppress',observe(intercepting),null);
check('decoy on firing origin can intercept',observe({...intercepting,z:-10}),null);
check('expired hologram cannot intercept',!!observe({...intercepting,left:0}),true);
check('destroyed hologram cannot intercept',!!observe({...intercepting,hp:0}),true);
check('cover continues to suppress',observe(distant,callback,undefined,player,()=>({x:0,z:-5})),null);
check('no charging shot',observe(distant,callback,[{...shooter(),state:'seek'},ally()]),null);
check('player intercepts first',observe(distant,callback,[shooter(),ally()],{x:0,z:-5}),null);
check('correct target identity',observe(distant).target.idx,1);
check('cue remains uncertain',V.cue(observe(distant)).includes('positions may change'),true);
check('no game score/damage logic in forecast module',typeof V.observe,'function');
const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
check('production call passes real TD.hitTime',index.includes('(d,ax,az,bx,bz)=>TD.hitTime(d,ax,az,bx,bz,T)'),true);
check('title remains at or beyond first repaired 2.79 build',/Aegis Verge 2\.(?:79|[89]\d|\d{3,})/.test(index),true);
console.log(`F3D79 decoy-aware forecast ${checks}/${checks} passed`);
