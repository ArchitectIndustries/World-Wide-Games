'use strict';
const assert=require('node:assert/strict');
const AM=require('../games/aegis-verge/arc-mines.js');
const T=require('../games/aegis-verge/tactics.js');
const BC=require('../games/aegis-verge/breachable-cover.js');
const CP=require('../games/aegis-verge/checkpoint.js');
let n=0;function eq(a,b,l){assert.deepEqual(a,b,l);n++}
const s=AM.create([{x:0,z:0},{x:12,z:0},{x:24,z:0}]);
const walls=[{id:0,x:3,z:0,w:1,d:2,h:3},{id:3,x:5,z:0,w:1,d:2,h:3},{id:5,x:0,z:8,w:2,d:2,h:3},{id:100,x:1,z:2,w:1,d:1,h:4}];
const hit=()=>AM.blastCover(s,0,walls,T.firstCover,BC.BREACHABLE_IDS).map(x=>x.id);
eq(hit(),[0],'first exposed wall only');
eq(AM.blastCover(s,0,[walls[0]],T.firstCover,BC.BREACHABLE_IDS).map(x=>x.id),[0],'single exposed wall');
eq(AM.blastCover(s,0,[walls[1]],T.firstCover,BC.BREACHABLE_IDS).map(x=>x.id),[3],'second wall face just in radius');
eq(AM.blastCover(s,0,[walls[2]],T.firstCover,BC.BREACHABLE_IDS),[],'outside radius');
eq(AM.blastCover(s,0,[walls[3]],T.firstCover,BC.BREACHABLE_IDS),[],'non-breachable excluded');
eq(AM.blastCover(s,-1,walls,T.firstCover,BC.BREACHABLE_IDS),[],'bad negative index');
eq(AM.blastCover(s,3,walls,T.firstCover,BC.BREACHABLE_IDS),[],'bad high index');
eq(AM.blastCover(null,0,walls,T.firstCover,BC.BREACHABLE_IDS),[],'bad state');
eq(AM.blastCover(s,0,{},T.firstCover,BC.BREACHABLE_IDS),[],'bad cover collection');
eq(AM.blastCover(s,0,walls,null,BC.BREACHABLE_IDS),[],'bad collider');
eq(AM.blastCover(s,0,walls,T.firstCover,null),[],'bad breakable list');
const bs=BC.create(walls);eq(BC.strike(bs,0,3).hp,2,'prior structural damage');
const pre=AM.blastTargets(s,0,[{x:4,z:0}],(o,a)=>!!T.firstCover(o.x,o.z,a.x,a.z,BC.live(bs),0.02));eq(pre.length,0,'pre-breach shielded actor');
const visible=AM.blastCover(s,0,BC.live(bs),T.firstCover,BC.BREACHABLE_IDS);eq(visible.map(x=>x.id),[0],'one first-hit wall');
eq(BC.strike(bs,0,2).breached,true,'mine finishes wall');
eq(BC.live(bs).some(x=>x.id===0),false,'physical cover collision removed');
eq(AM.blastTargets(s,0,[{x:4,z:0}],(o,a)=>!!T.firstCover(o.x,o.z,a.x,a.z,BC.live(bs),.02)).length,1,'new route opens next detonation');
eq(BC.snapshot(bs)[0],0,'checkpoint remembers breach');
eq(BC.restore(BC.create(walls),BC.snapshot(bs)),true,'valid restore');
const invalid=[{id:0,x:3,z:0,w:-1,d:2},{id:3,x:3,z:0,w:NaN,d:2}];eq(AM.blastCover(s,0,invalid,T.firstCover,BC.BREACHABLE_IDS),[],'invalid geometry ignored');
const cp=CP.validate({version:1,op:0,relay:1,hull:85,energy:72,score:320,recoveriesLeft:1,elapsed:11,damageTaken:15,clean:false,savedAt:Date.now(),barrierHp:[0,5,5]});eq(cp.barrierHp,[0,5,5],'checkpoint schema retains structural breach');
console.log(JSON.stringify({suite:'F3D12 shockwave cover exposure and checkpoint',passed:n,total:n}));
