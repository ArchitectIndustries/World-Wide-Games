'use strict';
const assert=require('node:assert/strict');
const F=require('../games/aegis-verge/flux-slipways.js');
let n=0;const t=(label,fn)=>{fn();n++;};
t('two authored lanes',()=>assert.equal(F.TRACKS.length,2));
t('tracks frozen',()=>assert.ok(Object.isFrozen(F.TRACKS)));
t('fresh state',()=>assert.deepEqual(F.create(),{active:null,entries:0,distance:0,energySpent:0}));
t('departure forward qualifies',()=>assert.equal(F.sample({x:0,z:-22,energy:100},0,1,6)?.id,'departure'));
t('return backward qualifies',()=>assert.equal(F.sample({x:0,z:26,energy:100},0,-1,6)?.id,'return'));
t('return forward does not qualify',()=>assert.equal(F.sample({x:0,z:26,energy:100},0,1,6),null));
t('departure backward does not qualify',()=>assert.equal(F.sample({x:0,z:-22,energy:100},0,-1,6),null));
t('outside X no boost',()=>assert.equal(F.sample({x:5,z:-22,energy:100},0,1,6),null));
t('outside Z no boost',()=>assert.equal(F.sample({x:0,z:0,energy:100},0,1,6),null));
t('sideways no boost',()=>assert.equal(F.sample({x:0,z:-22,energy:100},1,0,6),null));
t('wrong diagonal no boost',()=>assert.equal(F.sample({x:0,z:-22,energy:100},.8,.6,6),null));
t('slow no boost',()=>assert.equal(F.sample({x:0,z:-22,energy:100},0,1,1),null));
t('reverse no boost',()=>assert.equal(F.sample({x:0,z:-22,energy:100},0,1,-7),null));
t('no energy no boost',()=>assert.equal(F.sample({x:0,z:-22,energy:0},0,1,6),null));
t('threshold energy qualifies',()=>assert.equal(F.sample({x:0,z:-22,energy:12},0,1,6)?.id,'departure'));
t('below energy threshold no boost',()=>assert.equal(F.sample({x:0,z:-22,energy:11.99},0,1,6),null));
t('disabled no boost',()=>assert.equal(F.sample({x:0,z:-22,energy:100},0,1,6,false),null));
t('malformed coordinate fail closed',()=>assert.equal(F.sample({x:NaN,z:-22,energy:100},0,1,6),null));
t('malformed energy fail closed',()=>assert.equal(F.sample({x:0,z:-22,energy:NaN},0,1,6),null));
t('first trip charges finite energy',()=>{const p={energy:80},s=F.create();let v=F.advance(s,F.TRACKS[0],.1,1,p);assert.equal(v.entered,true);assert.ok(Math.abs(p.energy-77.7)<1e-8);assert.equal(s.entries,1);});
t('entry is edge triggered',()=>{const s=F.create(),p={energy:100};F.advance(s,F.TRACKS[0],.1,1,p);assert.equal(F.advance(s,F.TRACKS[0],.1,1,p).entered,false);});
t('leave clears active',()=>{const s=F.create(),p={energy:100};F.advance(s,F.TRACKS[0],.1,1,p);assert.equal(F.advance(s,null,.1,0,p).active,false);assert.equal(s.active,null);});
t('reentry counts distinct event',()=>{const s=F.create(),p={energy:100};F.advance(s,F.TRACKS[0],.1,1,p);F.advance(s,null,.1,0,p);F.advance(s,F.TRACKS[0],.1,1,p);assert.equal(s.entries,2);});
t('zero actual motion does not cost',()=>{const s=F.create(),p={energy:100};const v=F.advance(s,F.TRACKS[0],.1,0,p);assert.equal(v.spent,0);assert.equal(p.energy,100);});
t('bounded timestep cost',()=>{const s=F.create(),p={energy:100};F.advance(s,F.TRACKS[0],4,1,p);assert.equal(p.energy,100-.25*F.COST);});
t('never negative energy',()=>{const s=F.create(),p={energy:.1};F.advance(s,F.TRACKS[0],.1,1,p);assert.equal(p.energy,0);});
t('low-tier geometry bounded',()=>{let c=0;F.render({cube(){c++;}},true,null,true,0);assert.ok(c<=30);});
t('full-tier geometry bounded',()=>{let c=0;F.render({cube(){c++;}},false,null,false,0);assert.ok(c<=50);});
t('no mutable shared state',()=>{const a=F.create(),b=F.create();a.entries=20;assert.equal(b.entries,0);});
t('track bounds consistent',()=>assert.ok(F.TRACKS.every(r=>r.width>2&&r.length>10&&r.x===0)));
console.log(`F3D45 Flux Slipways ${n}/${n} passed`);
