'use strict';
const assert=require('node:assert/strict');
const C=require('../games/aegis-verge/skyburst-counterpulse.js');
const SB=require('../games/aegis-verge/siege-barrage.js');
const T=require('../games/aegis-verge/tactics.js');
let n=0;const ok=(name,value)=>{assert.ok(value,name);n++};
const sh=(p=.75)=>({fromX:0,fromZ:0,x:0,z:16,left:SB.FLIGHT*(1-p),total:SB.FLIGHT,casterIdx:1});
const act=(x=0,z=12)=>({x,z});
const neutral=(list,actor=act(),blocks=[],r=10)=>C.intercept(list,actor,blocks,T.firstCover,r);
let shell=sh(.75),p=C.position(shell);
ok('actual trajectory progress is fraction from left/total',Math.abs(p.progress-.75)<1e-7);
ok('real shell x/z travels from caster to marked landing point',Math.abs(p.x)<1e-7&&Math.abs(p.z-12)<1e-7);
ok('airborne 3D arc is the same as rendered projectile arc',Math.abs(p.y-(1.4+44*.75*.25))<1e-7);
ok('apex height is above 10m pulse when player is on ground',C.position(sh(.5)).y>11);
ok('non-physical expiring shell cannot be pulsed',C.position({...shell,left:0})===null);
ok('missing total is rejected',C.position({...shell,total:0})===null);
ok('NaN coordinates are rejected',C.position({...shell,fromX:NaN})===null);
let list=[sh(.75)],hits=neutral(list);
ok('genuine reachable flying shell neutralized',hits.length===1&&list.length===0);
ok('returned 3D collision uses actual airborne position',hits[0].y>8&&hits[0].y<11);
list=[sh(.5)];ok('full-height apex is safely unreachable',neutral(list,act(0,8)).length===0&&list.length===1);
list=[sh(.75)];ok('pulse fired from distant point cannot remove shell',neutral(list,act(30,30)).length===0&&list.length===1);
list=[sh(.75)];ok('intact wall obstructs pulse',neutral(list,act(0,8),[{id:1,x:0,z:9,w:5,d:1}],10).length===0&&list.length===1);
list=[sh(.75)];ok('no wall no occlusion',neutral(list,act(0,8),[],10).length===1);
list=[sh(.75),sh(.75)];ok('two valid shells each independently neutralized',neutral(list).length===2&&list.length===0);
list=[sh(.75),sh(.5)];ok('mixed reach preserves unreachable shell',neutral(list).length===1&&list.length===1&&Math.abs(list[0].left-SB.FLIGHT*.5)<1e-8);
list=[sh(.75)];ok('invalid radius cannot remove shell',neutral(list,act(),[],0).length===0&&list.length===1);
ok('bad actor is rejected',neutral(list,{x:NaN,z:0}).length===0&&list.length===1);
ok('nonarray shells safely rejected',neutral(null).length===0);
ok('invalid cover callback safely rejected',C.intercept(list,act(),[],null,10).length===0&&list.length===1);
ok('pulse never mutates caster HP or score',(()=>{let score=31,e={hp:8},shells=[sh(.75)];neutral(shells);return score===31&&e.hp===8;})());
const effects=[];C.emit(effects,[p]);ok('interception emits first-party world-space marker',effects.length===1&&effects[0].y===p.y);
const fake={calls:0,cube(){this.calls++;}};C.render(fake,effects,false,false);ok('full detail renders bounded 9 cubes',fake.calls===9);
fake.calls=0;C.render(fake,effects,true,true);ok('calm low detail renders bounded 5 cubes',fake.calls===5);
C.tick(effects,0);ok('paused/no sim delta leaves marker unchanged',effects.length===1&&effects[0].left===.42);
C.tick(effects,.43);ok('simulated lifetime expires marker',effects.length===0);
let many=[];C.emit(many,Array.from({length:20},(_,i)=>({...p,x:i})));ok('effect pool capped to 6',many.length===6);
console.log(JSON.stringify({suite:'F3D41 Skyburst Counterpulse original 3D flight and score-neutral real Pulse interception',passed:n,total:n,failed:0}));
