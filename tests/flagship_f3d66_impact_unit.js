'use strict';
const assert=require('node:assert/strict');
const I=require('../games/aegis-verge/impact-direction.js');
let n=0;const ok=(name,value)=>{assert.ok(value,name);n++};
const make=(yaw=0)=>({x:0,z:0,yaw});
const s=I.create();
ok('fresh cue invisible',I.label(s)===''&&I.geometry(s,make()).length===0);
ok('no fabricated hit for null',!I.register(s,make(),null,10));
ok('no fabricated hit for zero damage',!I.register(s,make(),{x:0,z:9},0));
ok('no fabricated hit for missing source',!I.register(s,make(),{},9));
ok('no fabricated hit for coincident blast',!I.register(s,make(),{x:.01,z:.01},9));
ok('rear source recognized',I.register(s,make(),{x:0,z:-10},7)&&s.sector==='REAR');
ok('source damage in readable label',I.label(s).includes('REAR')&&I.label(s).includes('7 DAMAGE'));
ok('right source recognized',I.register(s,make(),{x:10,z:0},7)&&s.sector==='RIGHT');
ok('left source recognized',I.register(s,make(),{x:-10,z:0},7)&&s.sector==='LEFT');
ok('front source recognized',I.register(s,make(),{x:0,z:10},7)&&s.sector==='FRONT');
ok('front-right quadrant',I.register(s,make(),{x:5,z:5},7)&&s.sector==='FRONT RIGHT');
ok('rear-right quadrant',I.register(s,make(),{x:5,z:-5},7)&&s.sector==='REAR RIGHT');
ok('front-left quadrant',I.register(s,make(),{x:-5,z:5},7)&&s.sector==='FRONT LEFT');
ok('rear-left quadrant',I.register(s,make(),{x:-5,z:-5},7)&&s.sector==='REAR LEFT');
ok('rotation-relative bearing',I.register(s,make(Math.PI/2),{x:0,z:8},7)&&s.sector==='LEFT');
ok('low detail reduces geometry',I.geometry(s,make(),true).length===3);
ok('calm mode reduces geometry',I.geometry(s,make(),false,true).length===2);
ok('impact marks retain true world source after vehicle turns',(()=>{const first=I.geometry(s,make(),false)[0];const next=I.geometry(s,make(2.4),false)[0];return first.x===next.x&&first.z===next.z})());
ok('normal scene has five bounded markers',I.geometry(s,make()).length===5);
ok('no geometry NaNs',I.geometry(s,make()).every(v=>Number.isFinite(v.x)&&Number.isFinite(v.y)&&Number.isFinite(v.z)&&Number.isFinite(v.yaw)));
ok('render preserves frame input',(()=>{let c=0;return I.render({cube(){c++}},s,make())===5&&c===5})());
ok('time not advanced by negative',(()=>{let b=s.remaining;I.tick(s,-2);return s.remaining===b})());
ok('pause model leaves timer untouched',s.remaining===I.DURATION);
I.tick(s,.4);ok('timer decreases only on simulation tick',Math.abs(s.remaining-(I.DURATION-.4))<1e-7);
I.tick(s,4);ok('cue expires',s.remaining===0&&I.label(s)===''&&I.geometry(s,make()).length===0);
ok('score not defined on cue state',!Object.hasOwn(s,'score')&&!Object.hasOwn(s,'hull'));
ok('immutable exported API',Object.isFrozen(I)&&Object.isFrozen(I.SECTORS));
console.log(`F3D66 impact direction unit ${n}/${n} passed`);
