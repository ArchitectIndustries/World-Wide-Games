'use strict';
const assert=require('node:assert/strict');
const H=require('../games/aegis-verge/hostile-telegraphs.js');
let checks=0;const ok=(v,msg)=>{assert.ok(v,msg);checks++};
const base={state:'windup',type:'warden',x:0,z:0,yaw:0,aimX:0,aimZ:15,windup:.45,windupTotal:1.1};
const first=(ax,az,bx,bz,cover,r)=>cover.length?{x:0,z:8,t:.25}:null;
ok(H.lanes(base,[],first).length===3,'warden 3 lanes');
ok(H.pattern('bulwark').offsets.length===3,'bulwark 3 lanes');
ok(H.pattern('lancer').offsets.length===1,'lancer single');
ok(H.pattern('skirmisher').offsets.length===1,'skirmisher single');
ok(H.pattern('warden').speed===15,'warden same speed');
ok(H.pattern('lancer').speed===20,'lancer same speed');
ok(H.pattern('bulwark').speed===12,'bulwark same speed');
ok(H.pattern('skirmisher').speed===12,'skirmisher same speed');
let l=H.lanes(base,[],first);
ok(l.map(x=>x.offset).join(',')==='-0.1,0,0.1','exact offsets');
ok(Math.abs(l[1].angle)<1e-9,'aim direction center');
ok(Math.abs(l[0].angle+.1)<1e-9,'left spread exact');
ok(Math.abs(l[2].angle-.1)<1e-9,'right spread exact');
ok(l.every(x=>x.length<=H.MAX_DISTANCE+1e-8),'bounded distances');
ok(l.every(x=>!x.blocked),'unblocked');
ok(l[0].endX<0&&l[2].endX>0,'lane footprint flanks');
const clipped=H.lanes(base,[{x:0,z:8}],first);
ok(clipped.every(x=>x.blocked),'each lane physically clipped');
ok(clipped.every(x=>x.endZ===8),'each lane stops at hit');
ok(clipped.every(x=>x.length===8),'no warning through cover');
ok(H.lanes({...base,state:'seek'},[],first).length===0,'only real windup');
ok(H.lanes({...base,aimX:Infinity},[],first).length===0,'invalid aim rejects');
ok(H.lanes({...base,x:NaN},[],first).length===0,'invalid enemy position rejects');
ok(Object.isFrozen(H.VOLLEYS.warden.offsets),'firing pattern immutable');
const calls=[],engine={cube:(...a)=>calls.push(a)};
ok(H.render(engine,base,[],first,false,false)===7,'3 lanes 3 ticks 1 gun cue');
ok(calls.length===7,'cube count exact');
ok(calls.every(v=>Number.isFinite(v[0])&&Number.isFinite(v[2])),'finite geometry');
calls.length=0;ok(H.render(engine,base,[],first,true,true)===5,'mobile still displays every lane');
ok(calls.length===5,'low detail bounded');
ok(H.render(engine,{...base,state:'recover'},[],first)===0,'no false hazard after shot');
ok(H.lanes(base,[],first)[1].speed===H.pattern(base.type).speed,'visuals match actual volley speed');
console.log(JSON.stringify({suite:'F3D27 original hostile spread telegraphs',passed:checks,failed:0},null,2));
