'use strict';
// Regression for the menu that obscured Lattice Armada's live game.
// Actual shipped event handlers run in Node VM with modeled DOM/canvas.
// CSS is checked structurally; only browser QA can verify computed layout.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {boot}=require('./runtime-harness.cjs');
const html=fs.readFileSync(path.resolve(__dirname,'../../games/lattice-armada/index.html'),'utf8');
const checks=[];
const check=(name,value)=>{assert.ok(value,name);checks.push(name)};
check('Grid menu has an explicit hidden override',/\.menu\[hidden\]\s*\{[^}]*display\s*:\s*none\s*!important\s*;?[^}]*\}/.test(html));
check('Hidden menu explicitly disables pointer interception',/\.menu\[hidden\]\s*\{[^}]*pointer-events\s*:\s*none\s*;?[^}]*\}/.test(html));
const r=boot('lattice-armada',{origin:'https://worldwidegames.vercel.app/games/lattice-armada/'});
const el=id=>r.byId.get(id),key=(code,repeat=false)=>r.dispatch('keydown',{code,repeat});
check('Picker is initially shown',el('menu').hidden===false);
check('Picker renders four actual sector buttons',el('sectorGrid').querySelectorAll('button').length===4);
check('New pilot cannot select locked later sectors',el('sectorGrid').querySelectorAll('button').slice(1).every(b=>b.getAttribute('disabled')!==null));
el('launchBtn').click();
check('Launch hides the picker',el('menu').hidden===true);
check('Launch exposes Pause',el('pauseBtn').hidden===false&&el('pauseBtn').textContent==='Pause');
check('Launch hides Resume',el('resumeBtn').hidden===true);
key('KeyP');
check('Keyboard pause opens the picker',el('menu').hidden===false);
check('Keyboard pause exposes Resume',el('resumeBtn').hidden===false&&el('pauseBtn').textContent==='Paused');
key('KeyP',true);
check('Held P cannot immediately dismiss pause',el('menu').hidden===false);
el('resumeBtn').click();
check('Resume hides the picker and its Resume button',el('menu').hidden===true&&el('resumeBtn').hidden===true);
check('Resume restores Pause label',el('pauseBtn').textContent==='Pause');
el('pauseBtn').click();
check('Visible Pause control opens the picker',el('menu').hidden===false&&el('resumeBtn').hidden===false);
el('launchBtn').click();
check('Restart from the picker hides the picker',el('menu').hidden===true&&el('resumeBtn').hidden===true);
check('Restart restores fresh hull',Number(el('hullHud').textContent)===4);
el('pauseBtn').click();key('KeyR');
check('Keyboard restart closes an open pause picker',el('menu').hidden===true&&el('pauseBtn').textContent==='Pause');
r.dispatch('blur');
check('Losing focus opens the explicit pause picker',el('menu').hidden===false&&el('resumeBtn').hidden===false);
el('resumeBtn').click();
check('Resume cannot hide picker while focus is away',el('menu').hidden===false);
r.dispatch('focus');
check('Returning focus keeps the explicit pause state',el('menu').hidden===false);
el('resumeBtn').click();
check('Deliberate resume after focus return hides picker',el('menu').hidden===true);
r.document.hidden=true;r.dispatch('visibilitychange');
check('Hidden page pauses and shows picker',el('menu').hidden===false);
r.document.hidden=false;r.dispatch('visibilitychange');
check('Visible page still waits for deliberate resume',el('menu').hidden===false);
key('KeyP');
check('P resumes after visibility return',el('menu').hidden===true&&el('resumeBtn').hidden===true);
check('Launch, pause, resume and restart never award or persist a score',r.writes.length===0);
check('Served game exposes no mutable debug facade',!('__latticeArmada'in r.context));
console.log(JSON.stringify({suite:'Lattice Armada picker lifecycle',total:checks.length,passed:checks.length,qualification:'Actual first-party handlers in Node VM with modeled DOM/canvas plus a structural CSS assertion; no browser layout or physical-device claim.',checks},null,2));
