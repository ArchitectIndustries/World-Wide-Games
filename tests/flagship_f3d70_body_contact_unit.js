'use strict';
const assert=require('node:assert/strict');
const B=require('../games/aegis-verge/body-contact.js');
const T=require('../games/aegis-verge/tactics.js');
const TYPES={skirmisher:{size:1.4},lancer:{size:1.7},bulwark:{size:2.1},warden:{size:2.4}};
let n=0;const ok=(label,test)=>{assert.ok(test,label);n++};
function enemy(x,z,type='lancer'){return{x,z,type,hp:3,max:3,dead:false};}
function drive(from,end,es=[enemy(0,0)],walls=[]){const b={...end};return{body:b,result:B.clip(b,from,es,B.PLAYER_RADIUS,walls,T.free,TYPES)}}
const r=B.PLAYER_RADIUS+B.enemyRadius(enemy(0,0),TYPES);
ok('public API frozen',Object.isFrozen(B)&&B.PLAYER_RADIUS===1.15);
ok('real enemy radius scales with authored physics size',Math.abs(B.enemyRadius(enemy(0,0),TYPES)-1.7*.65)<1e-10);
ok('real living enemy intercepts swept long movement',(()=>{const t=drive({x:-6,z:0},{x:6,z:0});return t.result.hit&&t.body.x<0&&Math.hypot(t.body.x,t.body.z)>=r-.01})());
ok('no ghost through when entire step crosses body',drive({x:-20,z:0},{x:20,z:0}).body.x<0);
ok('clear lane passes normally',drive({x:-6,z:6},{x:6,z:6}).body.x===6);
ok('dead rig is not solid',drive({x:-5,z:0},{x:5,z:0},[{...enemy(0,0),dead:true}]).body.x===5);
ok('zero HP rig is not solid',drive({x:-5,z:0},{x:5,z:0},[{...enemy(0,0),hp:0}]).body.x===5);
ok('unknown type has no collision radius',drive({x:-5,z:0},{x:5,z:0},[{...enemy(0,0),type:'unknown'}]).body.x===5);
ok('explicit size works',B.enemyRadius({...enemy(0,0),size:3})===3*.65);
ok('invalid geometry ignored',B.enemyRadius({...enemy(0,0),size:-1},TYPES)>0);
ok('nonfinite position ignored',drive({x:-5,z:0},{x:5,z:0},[{...enemy(0,0),x:NaN}]).body.x===5);
ok('missing enemies safe',B.clip({x:1,z:1},{x:0,z:0},null,1,[],T.free).hit===false);
ok('invalid mover safe',B.clip({}, {x:0,z:0},[],1,[],T.free).hit===false);
ok('invalid radius safe',B.clip({x:1,z:1},{x:0,z:0},[],NaN,[],T.free).hit===false);
ok('stationary outside does not signal collision',drive({x:-5,z:0},{x:-5,z:0}).result.hit===false);
ok('move directly away from contact succeeds',drive({x:-r,z:0},{x:-r-2,z:0}).body.x<-r-1);
ok('parallel at contact is permitted',drive({x:-r,z:0},{x:-r,z:2}).body.z>1);
ok('existing overlap can escape outward',drive({x:-.5,z:0},{x:-4,z:0}).body.x<-3);
ok('existing overlap does not tunnel across center',drive({x:-.5,z:0},{x:4,z:0}).body.x<=-.5);
ok('live Warden blocks with larger physical radius',drive({x:-6,z:0},{x:6,z:0},[enemy(0,0,'warden')]).body.x<-(1.15+2.4*.65)+.02);
ok('multiple enemies earliest intercept',drive({x:-7,z:0},{x:7,z:0},[enemy(2,0),enemy(-2,0)]).body.x<-2);
ok('order-independent earliest enemy',drive({x:-7,z:0},{x:7,z:0},[enemy(-2,0),enemy(2,0)]).body.x<-2);
ok('real solid cover respected on attempted slide',(()=>{const b=drive({x:-3,z:-1},{x:2,z:1},[enemy(0,0)],[{id:1,x:-1,z:2,w:2,d:2}]);return T.free(b.body.x,b.body.z,[{id:1,x:-1,z:2,w:2,d:2}],B.PLAYER_RADIUS)})());
ok('enemy against actual player rig collides',(()=>{const e=enemy(-4,0),a={...e,x:4};const player={x:0,z:0,type:'rig',size:B.PLAYER_RADIUS/.65,hp:100};const out=B.clip(a,e,[player],1.7*.65,[],T.free,TYPES);return out.hit&&a.x<0})());
ok('no hull points damage mutation on collision',(()=>{const e=enemy(0,0),x=JSON.stringify(e),b={x:6,z:0,hull:64,energy:23,score:17};B.clip(b,{x:-6,z:0},[e],1.15,[],T.free,TYPES);return JSON.stringify(e)===x&&b.hull===64&&b.energy===23&&b.score===17})());
ok('calm indicator bounded to four cubes',(()=>{let c=0;const k=B.render({cube(){c++}},{x:0,z:0},.4,false,true);return k===4&&c===4})());
ok('low tier indicator bounded to four cubes',(()=>{let c=0;return B.render({cube(){c++}},{x:0,z:0},.4,true,false)===4&&c===4})());
ok('full indicator bounded to eight cubes',(()=>{let c=0;return B.render({cube(){c++}},{x:0,z:0},.4,false,false)===8&&c===8})());
ok('zero timer no indicator',B.render({cube(){throw Error('rendered')}},{x:0,z:0},0)===0);
ok('invalid coordinates no indicator',B.render({cube(){throw Error('rendered')}},{x:NaN,z:0},1)===0);
ok('circle intersection robust at no movement',B.circleTime({x:-5,z:0},{x:-5,z:0},enemy(0,0),2)===null);
ok('circle intersection finds geometric entry',Math.abs(B.circleTime({x:-5,z:0},{x:5,z:0},enemy(0,0),2)-.3)<1e-8);
ok('no intersection returns null',B.circleTime({x:-5,z:5},{x:5,z:5},enemy(0,0),2)===null);
console.log(`F3D70 body-contact ${n}/${n} passed`);
