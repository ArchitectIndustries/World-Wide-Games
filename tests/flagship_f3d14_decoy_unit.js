'use strict';
const assert=require('node:assert/strict');
const D=require('../games/aegis-verge/tactical-decoy.js');
const T=require('../games/aegis-verge/tactics.js');
let n=0; const ok=(v,msg)=>{assert.ok(v,msg);n++}; const eq=(a,b,msg)=>{assert.deepEqual(a,b,msg);n++};
const player={x:0,z:-27,yaw:0},d=D.create();
eq(D.visible(d),false,'starts inert');eq(D.ready(d,100,true),true,'ready when charged');
eq(D.ready(d,37,true),false,'low energy');eq(D.ready(d,100,false),false,'inactive cannot deploy');
eq(D.deploy(d,player,[],T,100,true),true,'forward deployment');
eq(d.z,-17,'10m ahead');eq(d.hp,2,'two hits');eq(d.left,D.DURATION,'duration');
eq(D.visible(d),true,'actually live');eq(D.target(d,{x:0,z:-12}).z,-17,'lures nearby drone');
eq(D.target(d,{x:40,z:20}),null,'distant drones keep normal target');
eq(D.target(d,{x:0,z:-12,dead:true}),null,'dead drones not targeted');
eq(D.ready(d,100,true),false,'no stacking');
eq(D.deploy(d,player,[],T,100,true),false,'cannot redeploy during lifespan');
eq(D.hitTime(d,0,-12,0,-22,T)!==null,true,'swept hostile impact hits lure');
eq(D.hitTime(d,0,-12,0,-14,T),null,'no ghost remote hit');
eq(D.absorb(d),true,'first hit absorbed');eq(d.hp,1,'one hit remains');
eq(D.absorb(d),true,'second hit absorbed');eq(D.visible(d),false,'shattered decoy disappears');eq(d.hp,0,'no negative hit points');
eq(D.absorb(d),false,'no extra score collision farming');eq(D.ready(d,100,true),false,'cooldown after destruction');
for(let i=0;i<50;i++)D.tick(d,.25);
eq(d.cooldown,0,'cooldown has elapsed');
eq(D.ready(d,100,true),true,'can deploy again');
const c=D.create();ok(D.deploy(c,player,[],T,100,true),'new lure deployed');
for(let i=0;i<22;i++)D.tick(c,.25);eq(c.left,0,'simulated six seconds expires');eq(c.hp,0,'expires without leftover hitbox');
const block=[{id:1,x:0,z:-23,w:5,d:3,h:3}];const b=D.create();eq(D.deploy(b,player,block,T,100,true),false,'solid wall blocks straight-line deployment');eq(b.left,0,'failure has no duration or cost');
const nearWall=[{id:2,x:0,z:-19,w:3,d:2,h:3}];const v=D.create();ok(D.deploy(v,player,nearWall,T,100,true),'deploys short of farther wall');ok(v.z <= -22 && v.z>=-24,'short placement remains on near side');ok(!T.firstCover(player.x,player.z,v.x,v.z,nearWall,.28),'no barrier clipping');
for(const input of [{x:NaN,z:0,yaw:0},{x:0,z:Infinity,yaw:0},{x:0,z:0,yaw:NaN},null])eq(D.deploy(D.create(),input,[],T,100,true),false,'invalid origin rejected');
eq(D.deploy(D.create(),player,null,T,100,true),false,'invalid cover rejected');
eq(D.deploy(D.create(),player,[],T,0,true),false,'no energy exploit');
eq(D.deploy(D.create(),player,[],T,100,false),false,'no prestart exploit');
for(const delta of [-1,0,NaN]){const x=D.create();D.deploy(x,player,[],T,100,true);eq(D.tick(x,delta),false,'invalid tick rejected');eq(x.left,D.DURATION,'duration preserved');}
const limit=D.create();D.deploy(limit,player,[],T,100,true);D.tick(limit,100);ok(limit.left>=D.DURATION-.25-.00001,'large timestep clamped');
console.log(JSON.stringify({suite:'F3D14 original decoy module',passed:n,total:n}));
