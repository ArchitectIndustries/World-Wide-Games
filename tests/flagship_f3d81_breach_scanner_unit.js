'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const scanner=require('../games/aegis-verge/breach-scanner.js');
const BC=require('../games/aegis-verge/breachable-cover.js');
const TRACE=require('../games/aegis-verge/shot-trace.js');
const T=require('../games/aegis-verge/tactics.js');
let n=0;function check(label,condition){assert.ok(condition,label);n++}
const wall={id:0,x:0,z:6,w:4,d:2,h:3};const solid={id:10,x:0,z:3,w:4,d:1,h:3};
const state=BC.create([wall,solid,{id:3,x:40,z:40,w:2,d:1,h:2},{id:5,x:-40,z:-40,w:2,d:1,h:2}]);
const player={x:0,z:0,yaw:0},mines={hp:[0],sites:[]};
const shot=(cover,enemies=[])=>TRACE.trace(player,cover,enemies,mines,0,T,35);
const clean=shot([wall]);let view=scanner.inspect(clean,state,BC);
check('actual first contact is cover 0',clean.kind==='cover'&&clean.target===0);
check('full HP readout',view?.hp===5&&view.max===5);
check('world marker uses actual wall height',view?.y===3.56);
check('accessible text shows physical armor',scanner.label(view).includes('ARMOR 5/5'));
check('closer permanent wall suppresses indicator',scanner.inspect(shot([solid,wall]),state,BC)===null);
check('enemy ahead of barrier suppresses indicator',scanner.inspect(shot([wall],[{x:0,z:2,type:'bulwark'}]),state,BC)===null);
check('clear line suppresses indicator',scanner.inspect(shot([]),state,BC)===null);
check('nonphysical hit suppresses',scanner.inspect({kind:'mine',target:0,x:0,z:3,distance:3},state,BC)===null);
check('nil hit suppresses',scanner.inspect(null,state,BC)===null);
check('invalid coordinate suppresses',scanner.inspect({...clean,x:NaN},state,BC)===null);
check('invalid ID suppresses',scanner.inspect({...clean,target:0.2},state,BC)===null);
BC.strike(state,0,2);view=scanner.inspect(clean,state,BC);
check('damage tracks authoritative state',view?.hp===3);
check('damage readout updates',scanner.label(view).includes('ARMOR 3/5'));
check('true 3d gauge draws 6 cubes in low mode',(()=>{let calls=0;const e={cube:()=>calls++};return scanner.render(e,view,true,true)===6&&calls===6;})());
check('full gauge adds a distinguishing marker',(()=>{let calls=0;const e={cube:()=>calls++};return scanner.render(e,view,false,false)===7&&calls===7;})());
check('no marker when idle',scanner.render({cube:()=>{throw Error('should not draw')}},null)===0);
check('checkpoint restore is visible',BC.restore(state,[4,5,5])&&scanner.inspect(clean,state,BC)?.hp===4);
BC.strike(state,0,5);
check('breached wall is not highlighted',scanner.inspect(clean,state,BC)===null);
check('breached wall exits live colliders',!BC.live(state).some(b=>b.id===0));
check('first-party module registered in game',fs.readFileSync('games/aegis-verge/index.html','utf8').includes('BREACHSCAN.inspect(shotLine,barriers,BC)'));
check('new module precached',fs.readFileSync('sw.js','utf8').includes('"./games/aegis-verge/breach-scanner.js"'));
console.log(`F3D81 cover-target unit assertions ${n}/${n} PASS`);
