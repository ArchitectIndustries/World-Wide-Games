'use strict';
const assert=require('node:assert/strict');
const S=require('../games/aegis-verge/siege-shockfront.js'),T=require('../games/aegis-verge/tactics.js');
let n=0;const ok=(condition,label)=>{assert.ok(condition,label);n++};
const origin={x:0,z:0};
for(const invalid of [null,{}, {x:NaN,z:0},{x:0,z:Infinity}]){ok(!S.begin(invalid,origin,4.2),'invalid body rejected');}
ok(!S.begin({x:9,z:0},origin,4.2),'out of range not pushed');
ok(!S.begin({x:0,z:0,dead:true},origin,4.2),'dead cannot be pushed');
ok(!S.begin({x:0,z:0},{x:NaN,z:0},4.2),'invalid origin');
const centered={x:0,z:0,yaw:0};ok(S.begin(centered,origin),'zero distance is deterministic');
ok(Number.isFinite(centered.skyburstShock.ux)&&Number.isFinite(centered.skyburstShock.uz),'zero distance directions are finite');
let before=centered.z;const free=S.advance(centered,.05,[],T.move,1.15);ok(centered.z>before&&free.moved>0,'player moves away over time');
ok(S.advance(centered,0,[],T.move,1.15).moved===0,'simulation freeze is respected');
for(let i=0;i<30;i++)S.advance(centered,1/60,[],T.move,1.15);
ok(centered.skyburstShock===null,'impulse finishes and frees actor');
ok(centered.z<4,'motion bounded; never teleports');
const wall=[{x:0,z:2,w:9,d:1,h:4}];const boxed={x:0,z:.25,yaw:0};
ok(S.begin(boxed,{x:0,z:-1},4.2),'blocked actor receives a real impulse');
for(let i=0;i<30;i++)S.advance(boxed,1/60,wall,T.move,1.15);
ok(boxed.z<=.35,'swept wall collision stops knockback');
ok(T.free(boxed.x,boxed.z,wall,1.15),'impulse cannot penetrate solid cover');
const bound={x:37.4,z:0,yaw:Math.PI/2};ok(S.begin(bound,{x:35,z:0},4.2),'near-world-edge actor affected');
for(let i=0;i<30;i++)S.advance(bound,1/60,[],T.move,.5);
ok(bound.x<=37.5+1e-6,'world bounds enforced');
const human={x:2,z:0},heavy={x:2,z:0},light={x:2,z:0};
for(const [o,kind] of [[human,'player'],[heavy,'bulwark'],[light,'skirmisher']])S.begin(o,origin,4.2,kind);
for(let i=0;i<25;i++)for(const o of [human,heavy,light])S.advance(o,1/60,[],T.move,.4);
ok(light.x>heavy.x,'light hostiles displace farther than heavy');
ok(human.x>heavy.x,'rig displacement remains physically bounded');
const list=[];for(let i=0;i<12;i++)S.emit(list,{x:i,z:0},false);
ok(list.length===S.MAX_BURSTS,'visual event count capped');
let calls=0;const engine={cube(){calls++}};S.render(engine,list,false,false);ok(calls===12*S.MAX_BURSTS,'high-quality ring bounded draw budget');
calls=0;S.render(engine,list,true,true);ok(calls===6*S.MAX_BURSTS,'calm ring bounded draw budget');
S.tick(list,.5);ok(list.length===0,'ring lifetime simulation time');
ok(typeof S.begin==='function'&&typeof S.advance==='function'&&Object.isFrozen(S),'first party shared API');
console.log(JSON.stringify({suite:'F3D43 original Skyburst Shockfront unit',passed:n,total:n}));
