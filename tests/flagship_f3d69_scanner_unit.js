'use strict';
const assert=require('node:assert/strict');
const S=require('../games/aegis-verge/conduit-scanner.js');
const A=require('../games/aegis-verge/armor-weakpoint.js');
const W=require('../games/aegis-verge/enemy-armor-wear.js');
let n=0;const ok=(name,value)=>{assert.ok(value,name);n++};
const player={x:8,z:0},enemy={x:0,z:0,yaw:0,hp:4,max:8,size:1.7,type:'lancer',dead:false};
const scan=(p=player,es=[enemy],cover=[],block=()=>null,range=27)=>S.observe(p,es,cover,block,range);
ok('frozen public API',Object.isFrozen(S)&&Object.isFrozen(S.TYPES));
ok('scanner detects right-hand real exposed conduit',scan()?.ready===true);
ok('matches actual weakpoint physical right face',A.evaluate(enemy,{vx:-45,vz:0},{x:1.1,z:0},1).bonus===1);
ok('matches actual half HP wear',W.stage(enemy)===2);
ok('returns exact reference',scan()?.enemy===enemy);
ok('right-side label accurate',S.cue(scan()).includes('RIGHT CONDUIT IN VIEW'));
ok('other-side label requires moving right',S.cue(scan({x:-8,z:0})).includes('move toward its RIGHT flank'));
ok('no false right-side lock',scan({x:-8,z:0})?.ready===false);
ok('front-face not right-side lock',scan({x:0,z:8})?.ready===false);
ok('partial right offset below threshold does not lock',scan({x:0.2,z:5})?.ready===false);
ok('half HP threshold inclusive',scan()?.enemy.hp===4);
ok('above half HP stays hidden',scan(player,[{...enemy,hp:5}])===null);
ok('full HP stays hidden',scan(player,[{...enemy,hp:8}])===null);
ok('zero HP stays hidden',scan(player,[{...enemy,hp:0}])===null);
ok('dead target stays hidden',scan(player,[{...enemy,dead:true}])===null);
ok('Warden no scanner',scan(player,[{...enemy,type:'warden'}])===null);
ok('unregistered type no scanner',scan(player,[{...enemy,type:'unknown'}])===null);
ok('invalid HP denominator no scanner',scan(player,[{...enemy,max:0}])===null);
ok('invalid yaw no scanner',scan(player,[{...enemy,yaw:NaN}])===null);
ok('invalid location no scanner',scan(player,[{...enemy,x:NaN}])===null);
ok('out of range hidden',scan({x:28,z:0})===null);
ok('explicit shorter range respected',scan(player,[enemy],[],()=>null,7)===null);
ok('wall blocks scouting',scan(player,[enemy],[],()=>({t:.3}))===null);
ok('cover receives real inputs',(()=>{let c=false;scan(player,[enemy],[{id:7}],(x,z,ex,ez,cv,margin)=>{c=margin===.08&&cv[0].id===7&&ex===0&&x===8;return null});return c})());
ok('nearest eligible nonoccluded target',scan(player,[{...enemy,x:5},{...enemy,x:2}])?.enemy.x===5);
ok('blocked closest target skips to next',scan(player,[{...enemy,x:5},{...enemy,x:2}],[],(x,z,ex)=>ex===5?{}:null)?.enemy.x===2);
ok('skirmisher eligible',scan(player,[{...enemy,type:'skirmisher'}])!==null);
ok('bulwark eligible',scan(player,[{...enemy,type:'bulwark'}])!==null);
ok('yaw rotation maps right world negative Z',scan({x:0,z:-8},[{...enemy,yaw:Math.PI/2}])?.ready===true);
ok('rotated other side is not ready',scan({x:0,z:8},[{...enemy,yaw:Math.PI/2}])?.ready===false);
ok('no gameplay mutation of target',(()=>{const old=JSON.stringify(enemy);scan();return JSON.stringify(enemy)===old})());
ok('no detection with invalid player',S.observe({},[enemy],[],()=>null)===null);
ok('no detection with invalid callback',S.observe(player,[enemy],[],null)===null);
ok('no detection with invalid enemies',S.observe(player,null,[],()=>null)===null);
ok('empty cue without target',S.cue(null)==='');
const cubes=[];const fake={cube(...a){cubes.push(a)}};
ok('full render has bounded four geometry calls',S.render(fake,scan(),1,false,false)===4&&cubes.length===4);
ok('low render bounded to two calls',(()=>{cubes.length=0;return S.render(fake,scan(),1,true,false)===2&&cubes.length===2})());
ok('blocked target never emits geometry',(()=>{cubes.length=0;return S.render(fake,null,1)===0&&cubes.length===0})());
ok('wrong flank never emits geometry',(()=>{cubes.length=0;return S.render(fake,scan({x:-8,z:0}),1)===0&&cubes.length===0})());
ok('render remains anchored on exact target right',(()=>{cubes.length=0;S.render(fake,scan(),1,true,true);return Math.abs(cubes[0][0]-enemy.size*.62)<1e-9})());
ok('calm render ignores time animation',(()=>{cubes.length=0;S.render(fake,scan(),1,true,true);const y=cubes[0][1];cubes.length=0;S.render(fake,scan(),5,true,true);return y===cubes[0][1]})());
console.log(`F3D69 scanner unit ${n}/${n} passed`);
