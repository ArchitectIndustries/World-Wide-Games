'use strict';
const assert=require('node:assert/strict');
const F=require('../games/aegis-verge/flux-trial.js');
let count=0;const check=(title,fn)=>{fn();count++};
const store=new Map(),storage=()=>({getItem:k=>store.get(k)??null,setItem:(k,v)=>store.set(k,v),removeItem:k=>store.delete(k)});
const gate=n=>({crossed:true,progress:n}),t=F.create(0,storage);
check('no previous record',()=>assert.equal(t.best,null));
check('ready indicator',()=>assert.match(F.display(t,0),/READY/));
check('refuse invented crossing without event',()=>assert.equal(F.cross(t,{crossed:false,progress:1},10,storage),null));
check('refuse gate skip',()=>assert.equal(F.cross(t,gate(2),10,storage),null));
check('first real crossing starts clock',()=>assert.equal(F.cross(t,gate(1),10,storage).kind,'start'));
check('start first split zero',()=>assert.deepEqual(t.splits,[0]));
check('refuse repeated first gate',()=>assert.equal(F.cross(t,gate(1),10.1,storage),null));
check('refuse negative elapsed',()=>assert.equal(F.cross(t,gate(2),-2,storage),null));
check('refuse missing elapsed',()=>assert.equal(F.cross(t,gate(2),NaN,storage),null));
check('refuse earlier clock value',()=>assert.equal(F.cross(t,gate(2),9,storage),null));
check('no added score authority',()=>assert.equal('score' in F,false));
check('no movement authority',()=>assert.equal('move' in F,false));
check('intermediate split accepted',()=>assert.equal(F.cross(t,gate(2),14,storage).time,4));
check('next split shows elapsed seconds',()=>assert.match(F.display(t,15),/RUN 5.0s/));
check('out-of-order fourth rejected',()=>assert.equal(F.cross(t,gate(4),16,storage),null));
check('third split accepted',()=>assert.equal(F.cross(t,gate(3),24,storage).time,14));
check('final split accepted',()=>assert.equal(F.cross(t,gate(4),42,storage).kind,'complete'));
check('four splits ordered',()=>assert.deepEqual(t.splits,[0,4,14,32]));
check('record persisted after readback',()=>assert.equal(t.stored,true));
check('best recorded',()=>assert.equal(F.read(storage,0).duration,32));
check('cannot complete twice',()=>assert.equal(F.cross(t,gate(4),44,storage),null));
const slower=F.create(0,storage);
for(let n=1;n<=4;n++)F.cross(slower,gate(n),n===1?10:10+n*12,storage);
check('slower run never overwrites best',()=>assert.equal(F.read(storage,0).duration,32));
check('slower run complete without new best',()=>assert.equal(slower.last.newBest,false));
const resumed=F.create(0,storage,true);
for(let n=1;n<=4;n++)F.cross(resumed,gate(n),n===1?10:10+n*2,storage);
check('resumed run explicitly ineligible',()=>assert.equal(resumed.last.ineligible,true));
check('resumed run cannot overwrite best',()=>assert.equal(F.read(storage,0).duration,32));
const unavailable=()=>{throw new Error('SecurityError')},fallback=F.create(1,unavailable);
for(let n=1;n<=4;n++)F.cross(fallback,gate(n),n===1?10:10+n*3,unavailable);
check('disabled storage does not interrupt gameplay',()=>assert.equal(fallback.complete,true));
check('blocked storage cannot claim saved best',()=>assert.equal(fallback.last.saved,false));
check('safe display when not saved',()=>assert.match(F.display(fallback,40),/FINISH/));
const key=F.key(0),old=store.get(key);
for(const bad of ['{','{"version":1,"duration":-3,"splits":[0,3,5,-3]}','{"version":1,"duration":8,"splits":[0,4,4,8]}','{"version":1,"duration":8,"splits":[0,4,6,9]}','{"version":1,"duration":8,"splits":[0,4,6,"8"]}']){
 store.set(key,bad);check('reject corrupt best record',()=>assert.equal(F.read(storage,0),null));
}
store.set(key,old);
check('reject invalid op',()=>assert.equal(F.read(storage,3),null));
check('operation records isolated',()=>assert.equal(F.read(storage,1),null));
const rapid=F.create(2,storage);F.cross(rapid,gate(1),1);check('reject same instant crossing',()=>assert.equal(F.cross(rapid,gate(2),1,storage),null));
console.log(`F3D48 Flux Split Trial ${count}/${count} assertions passed`);
