'use strict';
const assert=require('node:assert/strict');
const X=require('../games/aegis-verge/hostile-crossfire.js');
const T=require('../games/aegis-verge/tactics.js');
const types={skirmisher:{size:1.4},bulwark:{size:2.1},warden:{size:2.4}};
let n=0;function test(msg,v){assert.ok(v,msg);n++}
const seg=(a,b,c,d,e,f,g)=>T.segmentCircle(a,b,c,d,e,f,g);
const e=(x,z,type='skirmisher',idx=0,hp=3)=>({x,z,type,idx,hp,dead:false});
const path=(a,b,c,d)=>[{x:a,z:b},{x:c,z:d}];
const fire=(b,from,to,people,maxT=1)=>X.earliest(b,from,to,people,types,seg,maxT);
const [from,to]=path(-5,0,5,0);
test('API immutable',Object.isFrozen(X));
test('clear path no targets',fire({},from,to,[])===null);
test('single living ally receives swept impact',fire({source:{}},from,to,[e(0,0)])?.enemy.x===0);
test('closest impact normalized in segment range',fire({source:{}},from,to,[e(0,0)]).t>0);
test('earlier ally selected',fire({source:{}},from,to,[e(3,0),e(-2,0)])?.enemy.x===-2);
test('dead ignored',fire({source:{}},from,to,[{...e(-2,0),dead:true}])===null);
test('nonpositive hp ignored',fire({source:{}},from,to,[e(-2,0,'skirmisher',1,0)])===null);
test('source object excluded',(()=>{const shooter=e(0,0);return fire({source:shooter},from,to,[shooter])===null})());
test('other ally not excluded by source object',(()=>{const shooter=e(-4,0);const victim=e(0,0);return fire({source:shooter},from,to,[shooter,victim])?.enemy===victim})());
test('source id fallback safe',fire({sourceIdx:4},from,to,[e(0,0,'skirmisher',4)])===null);
test('no source id does not exclude ally with undefined index',fire({},from,to,[e(0,0)])?.enemy.x===0);
test('off-axis safe',fire({},from,to,[e(0,5)])===null);
test('exact tangent registers',fire({},from,to,[e(0,1.4*.65)])?.enemy.x===0);
test('threshold before target rejects',fire({},from,to,[e(0,0)],.1)===null);
test('target exactly within limit accepted',(()=>{const z=fire({},from,to,[e(0,0)]);return fire({},from,to,[e(0,0)],z.t)?.enemy.x===0})());
test('invalid start protected',fire({},{x:NaN,z:0},to,[e(0,0)])===null);
test('invalid end protected',fire({},from,{x:5,z:Infinity},[e(0,0)])===null);
test('invalid maxT protected',fire({},from,to,[e(0,0)],NaN)===null);
test('negative maxT protected',fire({},from,to,[e(0,0)],-1)===null);
test('invalid enemy location ignored',fire({},from,to,[e(NaN,0)])===null);
test('invalid enemy shape ignored',fire({},from,to,[e(0,0,'unsupported')])===null);
test('invalid callback safe',X.earliest({},from,to,[e(0,0)],types,null)===null);
test('invalid list safe',X.earliest({},from,to,null,types,seg)===null);
test('large hitbox accepts wider separation',fire({},from,to,[e(0,1.5,'warden')])?.enemy.x===0);
test('small hitbox rejects wider separation',fire({},from,to,[e(0,1.5,'skirmisher')])===null);
test('contact location interpolated',(()=>{const q=fire({},from,to,[e(0,0)]);return Math.abs(q.x-(from.x+(to.x-from.x)*q.t))<1e-9&&q.z===0})());
test('reverse flight matches',fire({},{x:5,z:0},{x:-5,z:0},[e(0,0)])!==null);
test('stationary overlapping bolt hits',fire({},{x:0,z:0},{x:0,z:0},[e(0,0)])?.t===0);
test('stationary noncontact does not hit',fire({},{x:-5,z:0},{x:-5,z:0},[e(0,0)])===null);
test('source remains excluded even at muzzle origin',(()=>{const shooter=e(0,0);return fire({source:shooter},{x:0,z:0},{x:0.2,z:0},[shooter])===null})());
console.log('F3D72 crossfire module '+n+'/'+n+' passed');
