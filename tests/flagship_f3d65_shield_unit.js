'use strict';
const assert=require('node:assert/strict');
const S=require('../games/aegis-verge/shield-fracture.js');
let count=0;
function check(desc,result){assert.ok(result,desc);count++;}
const near=(a,b)=>Math.abs(a-b)<1e-8;
const full=S.resolve(20,100,true);
check('normal full shield absorbs entire 20 hull',full.fullyBlocked&&near(full.spill,0));
check('normal full shield costs proportional energy',near(full.spent,16));
check('full shield never fractures',!full.fractured);
const weak=S.resolve(20,4,true);
check('4 charge cannot absorb 20 damage',near(weak.absorbed,5));
check('remaining 15 damage pierces',near(weak.spill,15));
check('weak shield consumes charge',near(weak.spent,4));
check('weak shield produces fracture',weak.fractured);
check('weak shield not marked fully blocked',!weak.fullyBlocked);
const empty=S.resolve(20,0,true);
check('zero-energy shield cannot absorb',near(empty.absorbed,0));
check('zero-energy shield passes full damage',near(empty.spill,20));
check('unshielded same damage still passes',near(S.resolve(20,100,false).spill,20));
check('unshielded consumes no charge',S.resolve(20,100,false).spent===0);
const edge=S.resolve(2,1,true);
check('minimum energy demand is respected',near(edge.absorbed,1));
check('minimum-demand partial hit breaches',near(edge.spill,1));
check('unused energy preserved on full block',near(S.resolve(10,24,true).spent,8));
check('no damage has no charge drain',S.resolve(0,1,true).spent===0);
check('negative damage rejected',(()=>{try{S.resolve(-1,2,true);return false}catch{return true}})());
check('invalid charge rejected',(()=>{try{S.resolve(1,NaN,true);return false}catch{return true}})());
check('result immutable',Object.isFrozen(edge));
check('shards stop after timer expiration',S.shards({x:1,z:2},0).length===0);
check('active full detail shards',S.shards({x:1,z:2},.3).length===10);
check('low detail reduces shards',S.shards({x:1,z:2},.3,true).length===6);
check('reduced motion static shards',S.shards({x:1,z:2},.3,false,true).length===4);
check('calm output location finite',S.shards({x:1,z:2},.3,false,true).every(p=>Number.isFinite(p.x)&&Number.isFinite(p.z)));
check('bad player yields no effects',S.shards(null,.4).length===0);
let n=0;let fake={cube:()=>n++};check('renderer returns count',S.render(fake,{x:0,z:0},.2)===10&&n===10);
check('no engine cannot draw',S.render(null,{x:0,z:0},.2)===0);
console.log('F3D65 Shield Fracture unit',count+'/'+count,'passed');
