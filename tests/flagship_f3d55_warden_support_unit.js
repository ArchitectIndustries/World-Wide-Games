ck('render uses amber signal',calls.some(c=>c[6]==='#fbbf24'));
ck('render holds elevated 3d position',calls.some(c=>c[1]>3));
ck('reduced effect draws only core beacon',S.render(engine,actors,true,true,5)===1);
ck('invalid engine skips rendering',S.render(null,actors)===0);
ward.dead=true;
ck('dead source suppresses beacon',S.render(engine,actors)===0);
ward.dead=false;ward.supportActive=false;
ck('inactive source suppresses beacon',S.render(engine,actors)===0);
ck('no renderer without actor list',S.render(engine,null)===0);
console.log(JSON.stringify({suite:'F3D55 Warden Reformation',pass:passes,fail:0}));
