'use strict';
const assert=require('node:assert/strict');
const E=require('../games/aegis-verge/elevated-cover.js');
const C=require('../games/aegis-verge/skyburst-counterpulse.js');
const T=require('../games/aegis-verge/tactics.js');
const SB=require('../games/aegis-verge/siege-barrage.js');
let n=0;function ok(desc,pred){assert.ok(pred,desc);n++;}
const a={x:0,z:7},p={x:0,y:1.1,z:7},shell=()=>({fromX:0,fromZ:0,x:0,z:16,left:SB.FLIGHT*.25,total:SB.FLIGHT,casterIdx:1});
const endpoint={x:0,y:C.position(shell()).y,z:12};
const low={id:1,x:0,z:9,w:5,d:1,h:3.2};
const tall={id:2,x:0,z:9,w:5,d:1,h:7};
const miss={id:3,x:7,z:9,w:2,d:1,h:10};
const batch=(blocks,r=10)=>{const list=[shell()];const hits=C.intercept(list,a,blocks,T.firstCover,r,E.blocked);return {list,hits};};
ok('rendered airborne shell passes low roofline',E.blocked(p,endpoint,[low])===null);
ok('ordinary ground-projected cover ray had blocked the same real shell',!!T.firstCover(a.x,a.z,endpoint.x,endpoint.z,[low],.08));
ok('roofline above actual 3d pulse ray blocks',E.blocked(p,endpoint,[tall])?.block.id===2);
ok('low wall before a tall wall never masks the taller hit',E.blocked(p,endpoint,[low,{...tall,id:4,z:10,h:11}])?.block.id===4);
ok('empty cover passes',E.blocked(p,endpoint,[])===null);
ok('off-axis wall does not block',E.blocked(p,endpoint,[miss])===null);
ok('a shell above the roofline is intercepted through live 3D geometry',batch([low]).hits.length===1);
ok('a shell below a tall roofline is not intercepted',batch([tall]).list.length===1);
ok('even after passing low roofline taller cover prevents exploitation',batch([low,{...tall,z:10,h:11}]).list.length===1);
ok('pulse outside 3D reach still cannot intercept',batch([low],4).list.length===1);
ok('missing height is fail closed for imported or malformed cover',batch([{id:1,x:0,z:9,w:5,d:1}]).list.length===1);
ok('negative height is fail closed',E.blocked(p,endpoint,[{...low,h:-5}])!==null);
ok('invalid point rejected without exception',E.blocked({x:NaN,y:1,z:0},endpoint,[low])===null);
ok('narrow near-zero movement ray inside volume reports block',E.blocked({x:0,y:1,z:9},{x:0,y:2,z:9},[low])!==null);
ok('narrow near-zero movement ray outside volume misses',E.blocked({x:10,y:1,z:9},{x:10,y:2,z:9},[low])===null);
ok('finite segment excludes wall behind endpoint',E.blocked(p,endpoint,[{...tall,z:17}])===null);
ok('finite segment excludes wall behind origin',E.blocked(p,endpoint,[{...tall,z:0}])===null);
ok('correct 3d cover callback does not spend energy or mutate score',(()=>{const list=[shell()],h=C.intercept(list,a,[low],T.firstCover,10,E.blocked);return h.length===1&&list.length===0;})());
const points=C.position(shell()),fx=[];C.emit(fx,[points],a);
ok('arc emitter keeps actual player origin at pulse height',fx[0].from.x===a.x&&fx[0].from.z===a.z&&fx[0].from.y===C.PULSE_Y);
const engine={calls:0,cube(){this.calls++}};C.render(engine,fx,false,false);
ok('full quality adds only five bounded 3d arc segments',engine.calls===14);
engine.calls=0;C.render(engine,fx,true,true);
ok('calm low tier uses two arc sparks not five',engine.calls===7);
const before=fx[0].left;C.tick(fx,0);
ok('pause freezes the counter-arc',fx[0].left===before);
C.tick(fx,.43);ok('counter-arc lifetime expires via sim clock',fx.length===0);
const old=[];C.emit(old,[points]);engine.calls=0;C.render(engine,old,false,false);
ok('legacy burst without origin stays compatible',engine.calls===9);
console.log(JSON.stringify({suite:'F3D42 bounded three-dimensional roofline Counterpulse and world-space arc',passed:n,total:n,failed:0}));
