'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const W=require('../games/aegis-verge/breach-concussion.js');
const BC=require('../games/aegis-verge/breachable-cover.js');
const T=require('../games/aegis-verge/tactics.js');
const CB=require('../games/aegis-verge/counterplay.js');
let n=0;const check=(name,result)=>{assert.ok(result,name);n++};
const block={id:0,x:0,z:0,w:2,d:2,h:3},solid={id:10,x:0,z:2,w:2,d:.7,h:3};
function enemy(x,z,state='windup'){return {x,z,type:'lancer',hp:3,dead:false,state,windup:5,aimX:12,aimZ:12,cool:0,staggerLeft:0,siegeTarget:{x:8}};}
const a=enemy(4,0),b=enemy(0,4),c=enemy(9,0),idle=enemy(3,3,'seek'),dead=enemy(4,2);dead.dead=true;
const all=[a,b,c,idle,dead];const state=W.create();const before=all.map(e=>e.hp);
const status=BC.create([block,solid]);check('breachable cover starts with five HP',BC.status(status,0).hp===5);
const hit=BC.strike(status,0,5);check('actual cover can be breached once',hit.breached===true);
const result=W.breach(state,block,all,BC.live(status),T,CB);
check('one uncovered charging hostile interrupted',result.count===1);
check('uncovered target enters active stagger',a.state==='stagger'&&a.staggerLeft===CB.STAGGER_SECONDS);
check('stagger cancels a prior charge target',a.siegeTarget===null&&a.aimX===a.x&&a.aimZ===a.z);
check('first-cover shields behind another wall',b.state==='windup');
check('outside eight-unit range never hit',c.state==='windup');
check('non-charging hostile never hit',idle.state==='seek');
check('dead enemy ignored',dead.dead&&dead.state==='windup');
check('no enemy damage applied',all.every((e,i)=>e.hp===before[i]));
check('counterplay exposes real follow-up',CB.shotDamage(a)===2);
check('one real event counted',state.events===1&&state.interrupted===1);
check('accessible label reflects result',W.label(state).includes('1 charged hostile interrupted'));
check('unblocked low geometry',(()=>{let cubes=0;return W.render({cube:()=>cubes++},state,true,false)===13&&cubes===13})());
check('reduced effects finite geometry',(()=>{let cubes=0;return W.render({cube:()=>cubes++},state,true,true)===8&&cubes===8})());
W.tick(state,.28);check('effect decays in sim time',state.left>.49&&state.left<.51);
W.tick(state,.55);check('expired effect and announcement clear',state.left===0&&W.label(state)==='');
check('expired effect renders nothing',W.render({cube:()=>{throw Error('stale render')}},state)===0);
W.clear(state);check('reset clears prior event',state.events===0&&state.left===0);
const ordinary=enemy(2,0,'seek');const post=W.breach(state,block,[ordinary],[],T,CB);
check('idle enemy produces zero false interruptions',post.count===0&&ordinary.state==='seek');
check('zero-interruption label is factual',W.label(state).includes('0 charged hostiles'));
check('invalid wall cannot affect AI',W.breach(state,{x:NaN,z:0},[enemy(2,0)],[],T,CB)===null);
check('missing raycast cannot create damage',W.breach(state,block,[enemy(2,0)],[],{},CB)===null);
check('module registered after scanner',fs.readFileSync(path.join(__dirname,'../games/aegis-verge/index.html'),'utf8').includes('<script src="breach-concussion.js"></script>'));
check('module precached by SW',fs.readFileSync(path.join(__dirname,'../sw.js'),'utf8').includes('./games/aegis-verge/breach-concussion.js'));
check('the original cannon collision still controls breach gate',fs.readFileSync(path.join(__dirname,'../games/aegis-verge/index.html'),'utf8').includes('if(result.breached){\n  cover=liveCover();\n  const concussion='));
console.log(`F3D82 breach concussion unit assertions ${n}/${n} PASS`);
