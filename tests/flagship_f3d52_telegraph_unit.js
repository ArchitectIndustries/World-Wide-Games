'use strict';
const assert=require('node:assert/strict');
const F=require('../games/aegis-verge/flux-phase-screens.js'), T=require('../games/aegis-verge/flux-phase-telegraph.js');
let n=0;const check=(name,test)=>{test();n++};
const first=F.SCREENS[0],last=F.SCREENS[1],start=5;
check('new screen timing export',()=>assert.equal(typeof F.timing,'function'));
check('clock remains read-only',()=>assert.ok(!('hit' in T)&&!('score' in T)&&!('move' in T)));
check('idle before start',()=>assert.equal(F.timing(first,5,null).mode,'idle'));
check('idle for invalid screen',()=>assert.equal(F.timing(null,5,0).mode,'idle'));
check('idle for reversed time',()=>assert.equal(F.timing(first,4,5).mode,'idle'));
const moment=u=>F.timing(first,start+u-first.offset+F.PERIOD,start);
for(const [at,mode] of [[0,'open'],[.8,'open'],[1.051,'warning'],[1.7,'warning'],[1.851,'live'],[3.1,'live'],[3.151,'open'],[3.59,'open'],[3.6,'open']]){
 check(`matching authoritative phase ${at}`,()=>assert.equal(moment(at).mode,F.phase(first,start+at-first.offset+F.PERIOD,start)));
 check(`expected named phase ${at}`,()=>assert.equal(moment(at).mode,mode));
}
check('open seconds',()=>assert.ok(Math.abs(moment(.5).seconds-(F.OPEN-.5))<1e-8));
check('warning seconds',()=>assert.ok(Math.abs(moment(1.2).seconds-(F.OPEN+F.WARN-1.2))<1e-8));
check('live seconds',()=>assert.ok(Math.abs(moment(2).seconds-(F.OPEN+F.WARN+F.LIVE-2))<1e-8));
check('last open wraps safely',()=>assert.ok(Math.abs(moment(3.25).seconds-(F.PERIOD-3.25))<1e-8));
check('time is pause safe',()=>assert.deepEqual(moment(2.1),moment(2.1)));
check('sensible next state',()=>assert.equal(moment(.2).next,'warning'));
check('warning next live',()=>assert.equal(moment(1.3).next,'live'));
check('live next open',()=>assert.equal(moment(2.2).next,'open'));
check('progress bounded',()=>assert.ok([0,.5,1.2,2.3,3.4].every(t=>moment(t).progress>=0&&moment(t).progress<=1)));
const off=F.create(),caps={hp:[0,2]};
check('offline status',()=>assert.equal(F.timing(first,5,0,caps).mode,'disabled'));
check('offline no remaining time',()=>assert.equal(F.timing(first,5,0,caps).seconds,null));
check('return remains live',()=>assert.equal(F.timing(last,start+2-last.offset+F.PERIOD,start,caps).mode,'live'));
check('status accessible',()=>assert.match(T.label(moment(2),first),/LIVE.*s/));
check('resolved screen explicit and not false live danger',()=>assert.match(T.label(moment(2),first,true),/CLEARED.*NO REPEAT STRIKE/));
check('no countdown before start',()=>assert.equal(T.label(F.timing(first,5,null),first),'STANDBY'));
check('offline reported as practice',()=>assert.match(T.label(F.timing(first,5,0,caps),first),/OFFLINE.*PRACTICE/));
let state=T.create(),p={x:0,z:first.z-5};
check('initial nearby live alert',()=>assert.match(T.observe(state,p,first,moment(2)),/SHIELD OR WAIT/));
check('no repeated spoken alert',()=>assert.equal(T.observe(state,p,first,moment(2)),null));
check('advance to safe clear announces once',()=>assert.match(T.observe(state,p,first,moment(3.2)),/CROSS WHEN CLEAR/));
check('away player does not hear threat',()=>assert.equal(T.observe(state,{x:0,z:first.z-25},first,moment(2)),null));
check('reapproach announces again',()=>assert.match(T.observe(state,p,first,moment(2)),/LIVE/));
check('other lane ignored',()=>assert.equal(T.observe(state,{x:8,z:first.z},first,moment(2)),null));
check('resolved crossing no redundant notification',()=>assert.equal(T.observe(state,p,first,moment(2),true),null));
check('offline has no live warning',()=>assert.equal(T.observe(state,p,first,F.timing(first,5,0,caps)),null));
check('stale screen has no warning',()=>assert.equal(T.observe(state,p,null,moment(2)),null));
check('warning announces only once',()=>assert.match(T.observe(state,p,first,moment(1.3)),/PREPARE TO STOP/));
check('no further warning without transition',()=>assert.equal(T.observe(state,p,first,moment(1.4)),null));
check('no score/mission state mutated by observation',()=>assert.deepEqual(off,F.create()));
let cubes=[],engine={cube:(...args)=>cubes.push(args)};
check('full 3D cue has bounded geometry',()=>assert.equal(T.render(engine,first,moment(2),false,false),19));
check('cue includes actual physical shutter plane',()=>assert.ok(cubes.every(x=>x[2]===first.z)));
check('full cue palette contains live danger',()=>assert.ok(cubes.some(x=>x[6]==='#fb7185')));
cubes=[];
