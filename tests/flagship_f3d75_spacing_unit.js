'use strict';
const assert=require('node:assert/strict');
const S=require('../games/aegis-verge/enemy-spacing.js');
const B=require('../games/aegis-verge/body-contact.js');
const T=require('../games/aegis-verge/tactics.js');
const types={skirmisher:{size:1.4},lancer:{size:1.7},bulwark:{size:2.1},warden:{size:2.4}};
let n=0;function ok(name,x){assert.ok(x,name);n++;}
const enemy=(x,z,id=0,hp=5,type='skirmisher')=>({x,z,idx:id,hp,max:5,type,dead:false});
const player={x:40,z:40,hull:100};
const near=enemy(0,0,1),moving=enemy(-4,0,2);
let o=S.obstacles(moving,player,[moving,near],B.PLAYER_RADIUS);
ok('API frozen',Object.isFrozen(S)&&S.FLASH>0);
ok('self excluded',!o.includes(moving));
ok('live ally included',o.includes(near));
ok('player proxy preserved',o.some(t=>t.type==='rig'&&Math.abs(t.size*.65-B.PLAYER_RADIUS)<1e-9));
ok('player list unchanged',S.obstacles(player,player,[moving,near],B.PLAYER_RADIUS).length===2);
ok('dead enemy excluded',S.obstacles(moving,player,[moving,{...near,dead:true}],B.PLAYER_RADIUS).length===1);
ok('zero HP excluded',S.obstacles(moving,player,[moving,{...near,hp:0}],B.PLAYER_RADIUS).length===1);
ok('negative nonfinite coordinates excluded',S.obstacles(moving,player,[moving,{...near,x:NaN}],B.PLAYER_RADIUS).length===1);
ok('player with zero hull excluded',S.obstacles(moving,{...player,hull:0},[moving,near],B.PLAYER_RADIUS).length===1);
ok('missing enemy array safe',S.obstacles(moving,player,null,B.PLAYER_RADIUS).length===1);
ok('no player radius excludes proxy',S.obstacles(moving,player,[moving,near],0).length===1);
const start={x:moving.x,z:moving.z};const body={x:4,z:0},clip=B.clip(body,start,o,types.skirmisher.size*.65,[],T.free,types);
ok('real swept enemy-enemy collision',clip.hit&&body.x<0);
ok('maintains typed physical separation',Math.hypot(body.x-near.x,body.z-near.z)>=2*types.skirmisher.size*.65-.02);
ok('enemy contact flashes',S.notice(moving,clip.obstacle,player)&&moving.spacingFlash===S.FLASH);
ok('real player contact not falsely flagged as hostile-to-hostile',!S.notice(moving,{type:'rig'},player));
ok('player self not flagged',!S.notice(player,near,player));
S.tick([moving],S.FLASH*.5);ok('flash ticks on sim time only',moving.spacingFlash<S.FLASH&&moving.spacingFlash>0);
S.tick([moving],S.FLASH);ok('flash expires',moving.spacingFlash===0);
S.notice(moving,near,player);S.tick([moving],0);ok('paused sim does not age flash',moving.spacingFlash===S.FLASH);
let count=0;const engine={cube(){count++}};
ok('low detail bounded at three cubes',S.render(engine,moving,true,false)===3&&count===3);
ok('calm detail bounded at three cubes',S.render(engine,moving,false,true)===3&&count===6);
ok('full detail bounded at six cubes',S.render(engine,moving,false,false)===6&&count===12);
ok('no phantom geometry after expiry',S.tick([moving],1)||S.render(engine,moving,false,false)===0);
const other=enemy(0,0,4);const passage={x:4,z:0},dead={...near,dead:true};B.clip(passage,{x:-4,z:0},S.obstacles(moving,player,[moving,dead],B.PLAYER_RADIUS),.91,[],T.free,types);
ok('defeated enemy remains traversable',passage.x===4);
ok('no score or HP changes in new subsystem',moving.hp===5&&near.hp===5&&player.hull===100);
console.log(`F3D75 spacing ${n}/${n} passed`);
