// The precache is a sealed public-resource snapshot. Never persist arbitrary
// runtime responses (including API data, redirects, or later build HTML).
const scope=self.registration.scope;
const publicURLs=new Set(ASSETS.map(asset=>new URL(asset,scope).href));
const navigationURLs=new Map();
for(const href of publicURLs){
  const url=new URL(href);
  if(url.search)continue;
  if(url.pathname.endsWith('/')||url.pathname.endsWith('.html')){
    navigationURLs.set(url.pathname,href);
    if(url.pathname.endsWith('/index.html')){
      const directory=url.pathname.slice(0,-'index.html'.length);
      if(!navigationURLs.has(directory))navigationURLs.set(directory,href);
    }
  }
}
async function cached(request){
  try{return await (await caches.open(CACHE)).match(request)}catch{return undefined}
}
self.addEventListener('install',event=>event.waitUntil(
  caches.open(CACHE).then(cache=>cache.addAll(ASSETS)).then(()=>self.skipWaiting())
));
self.addEventListener('activate',event=>event.waitUntil(
  caches.keys().then(keys=>Promise.all(
    keys.filter(key=>OWNED_CACHE.test(key)&&key!==CACHE).map(key=>caches.delete(key))
  )).then(()=>self.clients.claim())
));
self.addEventListener('fetch',event=>{
  const req=event.request;
  if(req.method!=='GET'||req.cache==='no-store'||req.headers.has('Authorization')||req.headers.has('Range'))return;
  const url=new URL(req.url);
  if(url.origin!==new URL(scope).origin)return;
  if(req.mode==='navigate'){
    const canonical=navigationURLs.get(url.pathname);
    if(!canonical)return;
    event.respondWith(fetch(req).catch(async error=>{
      const hit=await cached(canonical);
      if(hit)return hit;
      throw error;
    }));
    return;
  }
  if(!publicURLs.has(url.href))return;
  event.respondWith(cached(req).then(hit=>hit||fetch(req)));
});
